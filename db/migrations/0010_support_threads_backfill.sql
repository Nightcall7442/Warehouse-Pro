-- Завести поток на каждый разговор, у которого его ещё нет.
--
-- 0007 создавала support_threads и тем же файлом переносила туда по строке на
-- каждую пару «организация — человек» из support_messages. На боевом таблицу
-- уже создали руками мимо журнала, поэтому догон, дойдя до 0007, увидел
-- «таблица существует» и намеренно пропустил перепись: повтор задвоил бы
-- потоки, по два на один разговор, каждый со своим сроком хранения.
--
-- Без потока разговор существует только как строки в support_messages: экран
-- показывает чистый лист, а срок хранения к этим сообщениям не применяется —
-- очистка идёт по потокам. Новый заведётся лишь при следующем сообщении, а
-- старая переписка так и останется лежать вечно.
--
-- Здесь та же перепись, но идемпотентная: NOT EXISTS. Если потоки уже есть —
-- не вставит ничего; если их нет — заведёт ровно недостающие. Такую можно
-- прогонять сколько угодно раз, и её же не страшно догонять.
INSERT INTO `support_threads` (`tenant_id`, `user_id`, `opened_at`)
SELECT m.`tenant_id`, m.`user_id`, MIN(m.`created_at`)
FROM `support_messages` m
WHERE NOT EXISTS (
  SELECT 1 FROM `support_threads` t
  WHERE t.`tenant_id` = m.`tenant_id` AND t.`user_id` = m.`user_id`
)
GROUP BY m.`tenant_id`, m.`user_id`;
