UPDATE `stock_counts` sc INNER JOIN (SELECT `id`, ROW_NUMBER() OVER (PARTITION BY `tenant_id`, `number` ORDER BY `id`) AS `rn` FROM `stock_counts`) d ON d.`id` = sc.`id` SET sc.`number` = CONCAT(sc.`number`, '-', d.`rn`) WHERE d.`rn` > 1;
-- Номер инвентаризации «ИНВ-N» брался как COUNT(*)+1 без уникального
-- индекса: два документа, заведённые в одну секунду, получали один номер.
-- Теперь каждая заявка оператора без права проводить правку — такой
-- документ, и совпадение номера путает историю движений («Ручная правка
-- №ИНВ-5» — которая из двух?). Следующая миграция ставит уникальный индекс
-- (tenant_id, number); до него повторы переименовываются: первый документ
-- сохраняет номер, следующие получают «-2», «-3». Идемпотентно: повтор
-- находит ноль строк.
