-- Время съёмки GPS-точки, отдельно от времени её получения сервером.
--
-- Точки копятся в буфере устройства, пока агент вне зоны покрытия, и
-- заливаются пачкой при первом же сигнале. Времени съёмки в них не было, и
-- сервер ставил время вставки: на карте супервайзера агент весь день «стоял»
-- на месте последней связи, а вечером мгновенно проезжал весь маршрут. На
-- вопрос «где ты был в два часа дня» ответить было нечем, хотя точка
-- физически сохранена.
--
-- Колонка НЕ заменяет created_at, а дополняет его, и это главное решение
-- здесь. Время съёмки приходит от клиента, проверить его нельзя, и строить на
-- нём проверку геозоны значило бы дать возможность задним числом «оказаться»
-- где угодно. Поэтому created_at остаётся временем получения сервером, на нём
-- продолжает работать anti-fraud, а recorded_at служит для показа на карте.
-- Расхождение между ними само по себе полезно: видно, что точка пролежала в
-- буфере три часа.
--
-- Колонка необязательная: у всех уже накопленных точек времени съёмки нет и
-- взять его неоткуда. Показ должен уметь обходиться created_at.
--
-- Идемпотентность сделана переносимо, через information_schema и
-- подготовленный запрос: `ADD COLUMN IF NOT EXISTS` — синтаксис MariaDB,
-- MySQL его отвергает, и на этом уже спотыкалась миграция 0038.

SET @col_exists := (
  SELECT COUNT(*) FROM information_schema.COLUMNS
  WHERE TABLE_SCHEMA = DATABASE()
    AND TABLE_NAME = 'agent_locations'
    AND COLUMN_NAME = 'recorded_at'
);
--> statement-breakpoint
SET @ddl := IF(@col_exists = 0,
  'ALTER TABLE `agent_locations` ADD COLUMN `recorded_at` timestamp NULL',
  'DO 0');
--> statement-breakpoint
PREPARE add_recorded_at FROM @ddl;
--> statement-breakpoint
EXECUTE add_recorded_at;
--> statement-breakpoint
DEALLOCATE PREPARE add_recorded_at;
