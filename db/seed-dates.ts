/**
 * Дата «n дней назад, в hourOffset часов от восьми утра» — и никогда в
 * будущем. Засев — история, а не план: сегодняшний заказ, датированный
 * вечером, при утреннем прогоне встаёт в списке ВЫШЕ только что
 * оформленного, и e2e «жизнь заказа» не находит свой заказ на первой
 * странице (оба PR 21.09.2026 упали в 12:46 UTC, вечерний прогон проходил).
 * Заодно «выручка сегодня» на главной не считает то, чего ещё не было.
 *
 * Откат «в прошлое» не уходит за полночь своего дня. Раньше он был «сейчас
 * минус до получаса», и засев сразу после полуночи клал сегодняшние визиты
 * во вчера: съёмка лендинга 25.09.2026 в 00:15 UTC показала «На сегодня
 * визитов нет» на «Моём дне» и «Плане».
 */
export function daysAgo(n: number, hourOffset = 0, now = Date.now()): Date {
  const d = new Date(now - n * 86_400_000);
  d.setHours(8 + hourOffset, Math.floor(Math.random() * 60), 0, 0);
  if (d.getTime() > now) {
    d.setTime(Math.max(new Date(d).setHours(0, 0, 0, 0), now - (1 + Math.floor(Math.random() * 30)) * 60_000));
  }
  return d;
}

/**
 * Событие через hours часов после base — но не позже «сейчас». Доставка и
 * слово магазина считались от createdAt плюс часы: сегодняшний заказ в
 * 12:20 получал «доставлен» в 17:20 и «подтверждён» в 21:20 — на «Контроле»
 * и у курьера было то, чего ещё не случилось.
 */
export function hoursAfter(base: Date, hours: number, now = Date.now()): Date {
  return new Date(Math.min(now, base.getTime() + hours * 3_600_000));
}
