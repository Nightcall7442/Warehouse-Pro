import { sql } from "drizzle-orm";
import { orders } from "@db/schema";

/*
  День, которым заказ стоит в комиссии агента, — день ПЕРВОЙ доставки.

  Решение владельца 23.11.2026 (бизнес-аудит 19.11.2026, пп. 15–16). Стояла
  дата оформления, и из-за неё:
    · заказ, оформленный 31.01 и доставленный 02.02, в январь не попадал (на
      момент утверждения не был доставлен), а в февраль — тоже (оформлен в
      январе): агент не получал комиссию вовсе;
    · заказ, возвращённый в работу, получал новую дату оформления
      (order-reopen.dateSecondLife) и после второй доставки входил в базу
      нового месяца, хотя комиссия за первый уже выплачена.
  Первая доставка не двигается при возврате в работу (first_delivered_at
  запоминает её до обнуления delivered_at), поэтому заказ стоит ровно в
  одном месяце. Дата оформления — запасной вариант для старых строк без даты
  доставки.

  Одно выражение на три места, где считается база: зарплата (kpi.ts),
  «Рассчитать» (commission-router.ts), разложение по товарам
  (commission-base.ts) — иначе они разошлись бы, а строка комиссии одна.
*/
export const commissionDay = sql`COALESCE(${orders.firstDeliveredAt}, ${orders.deliveredAt}, ${orders.createdAt})`;
