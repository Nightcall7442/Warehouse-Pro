/* ═══════════════════════════════════════════════════════════════════════════
   Возврат заказа из архива в работу.

   ── О чём речь ──────────────────────────────────────────────────────────────

   Заказ закрыт: доставлен, отменён или возвращён. Оператор ставит ему статус
   «новый» и проводит заново. Система это разрешает намеренно — ошибиться
   статусом легко, и поправить его надо уметь в обе стороны.

   Беда в том, что заказ при этом получает ВТОРУЮ ЖИЗНЬ, а понятия «круг» у
   него нет. Всё, что накопилось за первую жизнь, остаётся привязанным к тому
   же номеру: платежи, оформленные возвраты, отметка курьера, доставленные
   количества. Дальше каждое из них считается заново — и расходятся склад,
   долг и отчёты, причём молча.

   ── Что здесь решается ──────────────────────────────────────────────────────

   Не «поддержать второй круг целиком» — для этого нужен номер круга на
   заказе, на платежах, на возвратах и на движениях склада, то есть другая
   задача. Здесь решается более узкое и более честное:

     • пропускать в работу только те заказы, у которых второй круг ОДНОЗНАЧЕН;
     • отказывать словами там, где он неоднозначен, называя, что делать;
     • стирать следы первой жизни, которые иначе испортят вторую.

   ── Почему отказ, а не «как-нибудь посчитаем» ───────────────────────────────

   Два случая посчитать нельзя в принципе, а не «пока не написано».

   1. По заказу оформлен ВОЗВРАТ (документ «Возвраты», проведённый).
      Возврат уже вернул товар на склад и уменьшил долг магазина. Он привязан
      к заказу навсегда и вычитается при КАЖДОМ пересчёте. Проведи заказ
      второй раз — и те же единицы будут возвращены дважды: сначала
      документом, потом откатом статуса. Правильный ход здесь — новый заказ на
      то, что действительно повезут; старый остаётся историей вместе со своим
      возвратом.

   2. Заказ доставлен ЧАСТИЧНО (delivered_quantity меньше заказанного).
      Резерв под ним снят не на всё количество: недовезённый остаток вернулся
      в свободный остаток ещё при доставке. Строка заказа при этом говорит
      «десять», а держит шесть. Вернув такой заказ в работу, мы обязаны либо
      дозарезервировать четыре (а их может не быть на складе), либо оставить
      расхождение между заказанным и зарезервированным — и следующая доставка
      уведёт резерв в минус. Правильный ход тот же: новый заказ на остаток.

   ── Что стирается, когда отказа нет ─────────────────────────────────────────

   Поля первой доставки. Они не «история», они РАБОЧИЕ: по delivery_status
   курьер видит свои заказы, по нему же считалось «склад уже списан», а по
   delivered_quantity считается, сколько единиц заказ держит на складе.
   Оставить их — значит выдать вторую жизнь за продолжение первой.

   Платежи здесь НЕ трогаются намеренно. Они привязаны к заказу и вычитаются
   из его же суммы: заказ, оплаченный на первом круге, на втором и должен
   считаться оплаченным — магазин заплатил за этот товар один раз. Отвязывать
   или обнулять их значило бы переписывать деньги задним числом.
   ═══════════════════════════════════════════════════════════════════════════ */
import { TRPCError } from "@trpc/server";
import { and, eq } from "drizzle-orm";
import { orders, orderItems, returns } from "@db/schema";
import { holdsStock } from "../lib/order-status";

type Tx = Parameters<Parameters<ReturnType<typeof import("../queries/connection").getDb>["transaction"]>[0]>[0];

/**
 * Переход возвращает закрытый заказ в работу?
 *
 * Именно «закрытый → открытый», а не «любой назад»: delivered → cancelled
 * тоже идёт назад по смыслу, но заказ остаётся закрытым, второй жизни не
 * начинает и ничего из перечисленного выше не задевает.
 */
export function isReopen(from: string, to: string): boolean {
  return !holdsStock(from) && holdsStock(to);
}

/**
 * Отказ, написанный оператору, а не разработчику.
 *
 * Именно TRPCError, а не голый throw: подстраховка в middleware
 * (isOperatorFacingError) пропускает наверх только сообщения ровно класса
 * Error, короче двухсот знаков и без технических слов. Объяснение «почему
 * нельзя и что делать вместо этого» в эти рамки не укладывается — и было бы
 * молча подменено на «Внутренняя ошибка сервера. Попробуйте позже.»,
 * то есть отказ выглядел бы поломкой.
 */
const blocked = (message: string) => new TRPCError({ code: "BAD_REQUEST", message });

/**
 * Можно ли вернуть этот заказ в работу. Бросает отказ, если нельзя.
 *
 * Вызывается ВНУТРИ транзакции смены статуса и после блокировки строки
 * заказа: между проверкой и записью не должно поместиться ни оформление
 * возврата, ни доставка.
 */
export async function assertReopenable(
  tx: Tx,
  tenantId: number,
  orderId: number,
  orderNumber: string,
): Promise<void> {
  /*
    Обычные select и сравнение в JS, а не COUNT(*) и не сырое условие в WHERE.

    Тот же приём, что в returnedQuantitiesByProduct рядом, и по той же
    причине: строк здесь единицы, зато запрос остаётся внутри того куска
    построителя, который умеют служебные заглушки в тестах. Сырой sql`` они не
    исполняют — условие молча считалось бы истинным, и проверка отказывала бы
    всем подряд.
  */
  const completedReturns = await tx
    .select({ id: returns.id })
    .from(returns)
    .where(and(
      eq(returns.orderId, orderId),
      eq(returns.tenantId, tenantId),
      eq(returns.status, "completed"),
    ));

  if (completedReturns.length > 0) {
    throw blocked(
      `По заказу ${orderNumber} проведён возврат — вернуть его в работу нельзя. ` +
      `Возврат уже вернул товар на склад и уменьшил долг магазина, и второе ` +
      `проведение засчитает то же самое дважды. Оформите новый заказ на то, ` +
      `что действительно повезёте.`,
    );
  }

  /*
    Частичность ищется сравнением, а не «поле заполнено»: окно завершения
    проставляет delivered_quantity и при полной доставке тоже, и такие заказы
    возвращать в работу можно — резерв под ними снимался целиком.
  */
  const items = await tx
    .select({ quantity: orderItems.quantity, deliveredQuantity: orderItems.deliveredQuantity })
    .from(orderItems)
    .where(eq(orderItems.orderId, orderId));

  const partial = items.some(i =>
    i.deliveredQuantity != null && Number(i.deliveredQuantity) < Number(i.quantity));

  if (partial) {
    throw blocked(
      `Заказ ${orderNumber} доставлен частично — вернуть его в работу нельзя. ` +
      `Недовезённый остаток уже вернулся в свободный остаток склада, и заказ ` +
      `держит меньше товара, чем в нём записано. Оформите новый заказ на остаток.`,
    );
  }
}

/**
 * Переход отменяет уже состоявшуюся продажу?
 *
 * Отдельно от isReopen: заказ может уйти из «доставлен» и не начиная второй
 * жизни — например в «отменён». Выручка при этом всё равно откатывается, и
 * это событие, которое кто-то однажды придёт объяснять.
 */
export function reversesRevenue(from: string, to: string): boolean {
  return from === "delivered" && to !== "delivered";
}

/**
 * Стереть следы первой доставки.
 *
 * Зовётся ПОСЛЕ того, как складская разница уже посчитана и применена: она
 * считается по delivered_quantity, и обнулить его раньше значило бы вернуть
 * на склад не то количество, которое заказ на самом деле держал.
 */
export async function clearDeliveryTrace(tx: Tx, tenantId: number, orderId: number): Promise<void> {
  await tx.update(orders)
    .set({
      deliveryStatus: "not_assigned",
      deliveredAt:    null,
      deliveryResult: null,
      deliveryNotes:  null,
      // Курьер отвязывается намеренно: заказ поедет заново, и назначить его
      // могут другому. Пока courier_id оставался, заказ не показывался в
      // списке нового курьера и не показывался старому — тот его уже закрыл.
      courierId:      null,
      // Накладную второй жизни печатают заново, а отметка о печати осталась бы
      // от первой и врала бы «уже печатался».
      invoicePrintedAt: null,
    })
    .where(and(eq(orders.id, orderId), eq(orders.tenantId, tenantId)));

  await tx.update(orderItems)
    .set({ deliveredQuantity: null, returnReason: null })
    .where(eq(orderItems.orderId, orderId));
}

/**
 * Датировать вторую жизнь сегодняшним днём.
 *
 * ── Что было ────────────────────────────────────────────────────────────────
 *
 * `created_at` не двигался. Заказ, оформленный в январе, доставленный,
 * возвращённый в работу в марте и проведённый заново, оставался январским для
 * всей системы — а она датирует по нему почти всё:
 *
 *   • выручку за период (revenuePeriodConditions) и P&L,
 *   • комиссию агента (commission-router),
 *   • выполнение плана и квоты (sales-target-router),
 *   • спрос для прогноза остатков (stock-predictor).
 *
 * То есть деньги второго круга падали в месяц первого. Хуже, чем «падали»:
 * январь уже закрыт, отчёт по нему кто-то читал и на его основании
 * распределял, — и он менялся задним числом, молча, от правки статуса в марте.
 *
 * ── Почему двигается сама дата, а не добавляется вторая ─────────────────────
 *
 * Соблазн был обратный: завести `reopened_at` и писать всюду
 * COALESCE(reopened_at, created_at). Мест, где заказ датируется, — за
 * шестьдесят. Каждое пропущенное молча разошлось бы с соседним, и это ровно та
 * болезнь, которой система уже болела: фильтр удалённых заказов забыли в семи
 * файлах отчётности из восьми, и две цифры выручки на одной странице не
 * сходились. Одна забытая правка здесь стоила бы того же.
 *
 * Дата заказа — это дата его текущего круга. Система намеренно даёт заказу
 * второй круг под тем же номером; значит и дата у него вторая. Первая не
 * пропадает — она уходит в `first_ordered_at`, и туда же смотрит единственное
 * место, которому нужна именно она (старение долга, services/receivables.ts):
 * магазин должен с того дня, когда товар уехал ПЕРВЫЙ раз, и обнулять возраст
 * долга правкой статуса нельзя.
 *
 * В журнале правок событие уже пишется отдельно — `order.reopened`, — так что
 * «когда именно передатировали» восстанавливается и по нему.
 *
 * Первая дата запоминается только на ПЕРВОМ возврате: у заказа, побывавшего в
 * работе трижды, `first_ordered_at` остаётся самым ранним.
 */
export async function dateSecondLife(tx: Tx, tenantId: number, orderId: number): Promise<void> {
  /*
    Чтение и запись, а не COALESCE в одном UPDATE.

    Тот же приём и та же причина, что у assertReopenable выше: сырой sql``
    служебные заглушки в тестах не исполняют, и правило молча не проверялось
    бы вовсе. Строка заказа к этому моменту уже заблокирована `for update`.
  */
  const [row] = await tx
    .select({ createdAt: orders.createdAt, firstOrderedAt: orders.firstOrderedAt })
    .from(orders)
    .where(and(eq(orders.id, orderId), eq(orders.tenantId, tenantId)))
    .limit(1);
  if (!row) return;

  await tx.update(orders)
    .set({
      createdAt: new Date(),
      firstOrderedAt: row.firstOrderedAt ?? row.createdAt,
    })
    .where(and(eq(orders.id, orderId), eq(orders.tenantId, tenantId)));
}
