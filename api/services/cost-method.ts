/*
  Себестоимость товара при приходе — два правила на выбор организации.

  ── «Последняя закупка» (по умолчанию, как было всегда) ──────────────────
  Пришло по 60 000 — в карточке 60 000, сколько бы ни лежало по 55 000.
  Просто и понятно, но прибыль в P&L прыгает вместе с последней ценой.

  ── «Средняя по остатку» (просьба Serena Trade) ────────────────────────────
  Новая себестоимость — средневзвешенная того, что уже лежит, и того, что
  пришло: (остаток × старая + приход × новая) / (остаток + приход).
  100 ящиков по 55 000 и 10 по 60 000 дают 55 455, а не «(55 000 + 60 000) / 2»:
  простое среднее врёт, когда объёмы разные; при равных объёмах формулы
  совпадают. Считается от ОСТАТКА по всем складам до приёмки: то, что уже
  продано, в среднем не участвует — его себестоимость снята слепком в заказ.

  Ноль в приходе — «не трогать», как и прежде; ноль старой цены при остатке
  (карточка без себестоимости) — среднее берётся только от прихода, иначе
  пустая карточка «разбавляла» бы настоящую цену.
*/
export type CostMethod = "last" | "average";

export function nextCostPrice(method: CostMethod, onHandBefore: number, oldCost: number, qty: number, newCost: number): number {
  if (!(newCost > 0)) return oldCost;
  if (method !== "average" || !(qty > 0)) return newCost;
  const before = Math.max(0, onHandBefore);
  if (!(oldCost > 0) || before === 0) return newCost;
  return Math.round(((before * oldCost + qty * newCost) / (before + qty)) * 100) / 100;
}
