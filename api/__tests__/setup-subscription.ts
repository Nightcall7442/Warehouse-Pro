import { vi } from "vitest";

/**
 * По умолчанию в тестах подписка считается действующей.
 *
 * ── Зачем это понадобилось ──────────────────────────────────────────────────
 *
 * Проверка подписки переехала в основание authedQuery, то есть встала на пути
 * КАЖДОЙ процедуры. До этого она стояла на четырёх выделенных процедурах,
 * которых не вызывал никто, — потому организации с истёкшим тарифом и
 * продолжали работать.
 *
 * Побочный эффект правильного места: тридцать с лишним файлов, проверяющих
 * бизнес-логику заказов, склада и отчётов, начали получать отказ по оплате
 * раньше, чем доходили до предмета проверки. Ни один из них не про биллинг, и
 * заводить в каждом одинаковый мок значило бы тридцать раз написать одно и то
 * же — а потом забыть в тридцать первом.
 *
 * ── Почему это не прячет саму проверку ──────────────────────────────────────
 *
 * Умолчание здесь — «подписка есть», то есть тесты видят систему такой, какой
 * её видит оплативший клиент. Саму калитку стережёт api/__tests__/
 * subscription-gating.test.ts: он переопределяет этот мок своим и проверяет,
 * что при истёкшей подписке закрываются operatorQuery, adminQuery,
 * fieldSalesQuery и остальные рабочие процедуры, а billing и stripe остаются
 * открытыми. Убери кто-нибудь гейт из authedQuery — упадёт именно тот файл, и
 * упадёт внятно.
 *
 * Любой тест может переопределить умолчание своим vi.mock или vi.doMock.
 */
vi.mock("../lib/feature-gating", () => ({
  hasSubscriptionAccess: vi.fn(async () => true),
  checkSubscriptionAccess: vi.fn(async () => true),
  invalidateSubscriptionAccess: vi.fn(),
  getSubscriptionStatus: vi.fn(async () => null),
}));
