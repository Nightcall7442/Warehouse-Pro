import { describe, it, expect } from "vitest";
import { reminderSettled } from "../cron/debt-reminders";

/**
 * Напоминание о долге закрывается, когда долга больше нет.
 *
 * ── Чем это было ────────────────────────────────────────────────────────────
 *
 * Строка напоминания создаётся при частичной оплате и дальше рассылается по
 * сроку. Дважды в день, директору — в приложение и в телеграм, заголовком
 * «ПРОСРОЧЕННЫЙ ДОЛГ».
 *
 * Остаток считался как «сумма заказа минус оплаты». Возвратов в этой формуле не
 * было. Магазин, который вместо доплаты ВЕРНУЛ товар, оставался должен
 * навсегда: shops.debt у него падал до нуля (пересчёт долга возвраты знает), на
 * экране долгов он чист, а уведомление приходило каждый день — и никакое
 * действие в продукте его не гасило.
 *
 * ── Почему проверяется функцией, а не прогоном крона ─────────────────────────
 *
 * Внутри крона это решение окружено выборками, рассылкой и телеграмом. С
 * поддельной базой такой прогон проверяет в основном саму подделку. Правило
 * вынесено наружу и меряется числами — теми самыми, что видит человек.
 */

const order = (over: Record<string, unknown> = {}) => ({
  status: "delivered",
  paymentMethod: "cash",
  deletedAt: null,
  total: "300000",
  ...over,
});

describe("возврат закрывает долг наравне с деньгами", () => {
  it("вернул половину, доплатил половину — напоминание закрыто", () => {
    // Ровно тот случай, который слал уведомление вечно.
    expect(reminderSettled(order(), 150_000, 150_000)).toBe(true);
  });

  it("вернул весь товар — закрыто, даже если не платил вовсе", () => {
    expect(reminderSettled(order(), 0, 300_000)).toBe(true);
  });

  it("вернул часть, остальное не оплатил — напоминание живо", () => {
    // Обратная сторона: молча гасить всё подряд нельзя, долг настоящий.
    expect(reminderSettled(order(), 0, 100_000)).toBe(false);
  });

  it("ничего не вернул и не доплатил — живо", () => {
    expect(reminderSettled(order(), 100_000, 0)).toBe(false);
  });

  it("переплата и возврат сверх суммы — закрыто, а не «отрицательный долг»", () => {
    expect(reminderSettled(order(), 200_000, 200_000)).toBe(true);
  });
});

describe("заказ, который больше не должен", () => {
  /*
    Условие «заказ ещё должен» здесь то же, что в services/shop-debt.ts:
    живой, не отменённый и не возвращённый, и при этом либо долговой, либо уже
    доставленный. Похожее, но не совпадающее правило в этой системе уже
    приводило к расхождениям в деньгах.
  */
  it("отменённый — закрыто", () => {
    expect(reminderSettled(order({ status: "cancelled" }), 0, 0)).toBe(true);
  });

  it("возвращённый целиком — закрыто", () => {
    expect(reminderSettled(order({ status: "returned" }), 0, 0)).toBe(true);
  });

  it("удалённый как ошибка ввода — закрыто", () => {
    expect(reminderSettled(order({ deletedAt: new Date() }), 0, 0)).toBe(true);
  });

  it("не доставленный и не долговой — закрыто: товар ещё у нас", () => {
    expect(reminderSettled(order({ status: "processing" }), 0, 0)).toBe(true);
  });

  it("не доставленный, но оформленный В ДОЛГ — живо", () => {
    // Продажа в долг создаёт обязательство с оформления, а не с доставки.
    expect(reminderSettled(order({ status: "processing", paymentMethod: "debt" }), 0, 0)).toBe(false);
  });
});
