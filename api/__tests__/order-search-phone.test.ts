import { describe, it, expect } from "vitest";
import { phoneDigits } from "../lib/order-search";

/**
 * Когда строка поиска «Заказов» — телефон.
 *
 * Что было: поиск шёл по номеру заказа и названию магазина; телефон не
 * искался вовсе, а буквенное сравнение «90 123 45 67» с «+998901234567» не
 * совпало бы и после добавления столбца.
 *
 * Что проверяется: какие строки сводятся к цифрам номера, а какие остаются
 * номером заказа или словом. Что база по этим цифрам находит — на настоящей
 * MySQL: api/__tests__/real-db/orders-sort-search.test.ts.
 *
 * Нарочная поломка (проверено): порог «не меньше пяти цифр» убран — падает
 * «короткий набор»; снятие кода страны убрано — падает «код страны».
 */
describe("phoneDigits", () => {
  it("номер в любой записи — одни цифры", () => {
    expect(phoneDigits("90 123 45 67")).toBe("901234567");
    expect(phoneDigits("(90) 123-45-67")).toBe("901234567");
    expect(phoneDigits(" 90.123.45.67 ")).toBe("901234567");
  });

  it("код страны: полный номер находит и записанный без кода", () => {
    expect(phoneDigits("+998 90 123 45 67")).toBe("901234567");
    expect(phoneDigits("998901234567")).toBe("901234567");
    // Неполный номер с кодом — как набран: он и так подстрока записи с кодом.
    expect(phoneDigits("+998 90 12")).toBe("9989012");
  });

  it("короткий набор — номер заказа, а не телефон", () => {
    expect(phoneDigits("1490")).toBeNull();
    expect(phoneDigits("45 67")).toBeNull();
  });

  it("слова и номера заказов телефоном не считаются", () => {
    expect(phoneDigits("Хумо")).toBeNull();
    expect(phoneDigits("№14900")).toBeNull();
    expect(phoneDigits("ORD-B650EBBC369B")).toBeNull();
    expect(phoneDigits("")).toBeNull();
  });
});
