/**
 * Пробел на краю переменной ломает подпись молча.
 *
 * ── Что случилось ───────────────────────────────────────────────────────────
 *
 * Пароль хранилища вписали в панель Railway с лишним пробелом на конце —
 * обычная опечатка при вставке. MinIO при чтении своей переменной пробелы
 * обрезает, наш клиент S3 — нет. Хранилище отвечало SignatureDoesNotMatch, при
 * этом значения выглядели одинаковыми до последнего символа: одна длина, один
 * отпечаток. Нашлось только сравнением байт за байтом.
 *
 * ── Почему чинится в корне ──────────────────────────────────────────────────
 *
 * Так же молча ломается ЛЮБОЙ секрет, который сверяют посимвольно: ключ крона,
 * секрет вебхука телеграма, токен метрик. Каждый из них сравнивается точным
 * равенством, и лишний пробел даёт «не совпало» без единой подсказки, в чём
 * дело.
 *
 * Пробел на краю не значит ничего ни в одной переменной этого приложения — ни
 * в адресе, ни в токене, ни в списке через запятую. Поэтому снимается один раз
 * при чтении, а не в каждом месте, где об этом вспомнят.
 */
import { describe, it, expect, beforeEach, afterEach, vi } from "vitest";

const SAVED = { ...process.env };

beforeEach(() => {
  vi.resetModules();
  process.env.APP_SECRET = "секрет-для-проверки";
  process.env.DATABASE_URL = "mysql://root@127.0.0.1:3306/test";
});

afterEach(() => {
  process.env = { ...SAVED };
});

async function loadEnv() {
  return (await import("../lib/env")).env;
}

describe("чтение переменных", () => {
  it("снимает пробелы с необязательной переменной", async () => {
    process.env.S3_SECRET_KEY = "  тайна  ";
    expect((await loadEnv()).s3SecretKey).toBe("тайна");
  });

  it("снимает перевод строки — его добавляет вставка из буфера", async () => {
    process.env.S3_ACCESS_KEY = "warehouse\n";
    expect((await loadEnv()).s3AccessKey).toBe("warehouse");
  });

  it("снимает пробелы и с обязательной", async () => {
    // APP_SECRET подписывает сессии: лишний пробел здесь означал бы, что после
    // правки переменной перестают открываться все сессии разом.
    process.env.APP_SECRET = " подпись-сессий ";
    expect((await loadEnv()).appSecret).toBe("подпись-сессий");
  });

  it("внутренние пробелы остаются", async () => {
    process.env.SMTP_FROM = "  Склад Про <no-reply@example.com>  ";
    expect((await loadEnv()).smtpFrom).toBe("Склад Про <no-reply@example.com>");
  });

  it("внутренние переводы строк остаются", async () => {
    /*
      trim() трогает только края. Многострочное значение — ключ в формате PEM,
      например — должно дойти целым.

      Загрузка модуля одна на проверку: env собирается при импорте, и второе
      чтение в том же тесте вернуло бы уже собранное.
    */
    process.env.S3_SECRET_KEY = "  первая\nвторая  ";
    expect((await loadEnv()).s3SecretKey).toBe("первая\nвторая");
  });

  it("незаданная переменная берёт запасное значение", async () => {
    delete process.env.S3_REGION;
    delete process.env.APP_URL;
    const env = await loadEnv();
    expect(env.s3Region).toBe("");
    expect(env.appUrl).toBe("http://localhost:3000");
  });

  it("переменная из одних пробелов считается незаданной", async () => {
    // Иначе она проходит все проверки «задано ли» и валит запрос уже в
    // хранилище — там, где причина не видна.
    process.env.S3_SECRET_KEY = "   ";
    expect((await loadEnv()).s3SecretKey).toBe("");
  });
});
