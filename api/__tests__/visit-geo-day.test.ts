import { describe, it, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";
import { cleanTrack } from "../services/visit-geo";
import { haversineKm } from "@contracts/geo";

/**
 * Как прошёл день: пробег, время в точках и шаги визита.
 *
 * ── Что было ────────────────────────────────────────────────────────────────
 *
 * Координаты пишутся в agent_locations с самого начала — точка раз в пару
 * минут. Читались они РОВНО в одном месте: «где все сейчас» на карте, по
 * последней точке на человека. Весь остальной день лежал в базе и не отвечал
 * ни на один вопрос: где ездил, сколько простоял в точке, сколько намотал.
 *
 * Сам визит при этом — одна кнопка: status = visited, visitedAt = сейчас. Ни
 * времени прихода, ни ухода, ни координат в момент отметки.
 *
 * ── Почему шаги восстанавливаются, а не записываются ────────────────────────
 *
 * Кнопки «пришёл / ушёл» живут в мобильном приложении, а оно в другом
 * репозитории и выкладывается отдельно. Ручка под них стала бы седьмой
 * написанной и никем не вызываемой — в этом продукте таких уже полдюжины.
 * Разбор пингов работает сегодня, и у него есть своё преимущество: нажать
 * «пришёл», сидя дома, можно, а подделать след — труднее.
 *
 * ── Что проверяется здесь ───────────────────────────────────────────────────
 *
 * Очистка следа. Она и решает, будет ли пробег числом, которому верят: один
 * выброс приёмника добавляет к дню полсотни километров, и тогда весь экран
 * можно выбрасывать.
 */
const T = (hhmm: string) => new Date(`2026-09-10T${hhmm}:00`);

/** Ташкент, две точки примерно в километре друг от друга. */
const A = { lat: 41.311, lng: 69.240 };
const B = { lat: 41.320, lng: 69.240 };

describe("очистка следа", () => {
  it("точки идут по времени, даже если пришли вперемешку", () => {
    // Буферные точки приезжают пачкой и не по порядку.
    const out = cleanTrack([
      { ...B, at: T("10:05") },
      { ...A, at: T("10:00") },
    ]);
    expect(out.map(p => p.at.getMinutes())).toEqual([0, 5]);
  });

  it("неточные точки выбрасываются", () => {
    /*
      Телефон в кармане в подвале отдаёт координату с погрешностью в
      километры: где человек был, она не сообщает, а к пробегу добавляет пару
      километров туда и обратно.
    */
    const out = cleanTrack([
      { ...A, at: T("10:00"), accuracy: 15 },
      { lat: 41.5, lng: 69.5, at: T("10:02"), accuracy: 3000 },
      { ...B, at: T("10:04"), accuracy: 20 },
    ]);
    expect(out).toHaveLength(2);
    expect(out.every(p => p.lat < 41.4)).toBe(true);
  });

  it("прыжок приёмника не попадает в пробег", () => {
    /*
      Ровно то, из-за чего дневному пробегу нельзя было верить: одиночный
      выброс уводит точку за сотню километров и возвращает обратно. Точность
      при этом бывает отличной — фильтром по accuracy такое не ловится.
    */
    const out = cleanTrack([
      { ...A, at: T("10:00"), accuracy: 10 },
      { lat: 42.5, lng: 70.5, at: T("10:01"), accuracy: 10 }, // ~150 км за минуту
      { ...B, at: T("10:02"), accuracy: 10 },
    ]);
    expect(out, "прыжок остался в следе").toHaveLength(2);
  });

  it("две точки одной секундой не считаются бесконечной скоростью", () => {
    // Деление на ноль здесь выбросило бы нормальную точку частой записи.
    const out = cleanTrack([
      { ...A, at: T("10:00"), accuracy: 10 },
      { lat: 41.3111, lng: 69.2401, at: T("10:00"), accuracy: 10 },
    ]);
    expect(out).toHaveLength(2);
  });

  it("точность не сообщили — точку берём", () => {
    // Старые сборки приложения accuracy не шлют вовсе; выбросив их, мы
    // потеряли бы весь след у части агентов.
    const out = cleanTrack([{ ...A, at: T("10:00") }, { ...B, at: T("10:10") }]);
    expect(out).toHaveLength(2);
  });

  it("пустой день — пустой след, без выдумок", () => {
    expect(cleanTrack([])).toEqual([]);
  });
});

describe("расстояние", () => {
  it("километр остаётся километром", () => {
    // Опора для порогов выше: без неё «150 км/ч» проверяет само себя.
    const km = haversineKm(A.lat, A.lng, B.lat, B.lng);
    expect(km).toBeGreaterThan(0.9);
    expect(km).toBeLessThan(1.1);
  });
});

// ── Разбор исходников ────────────────────────────────────────────────────────
const read = (p: string) => fs.readFileSync(path.resolve(process.cwd(), p), "utf8").replace(/\r\n/g, "\n");
const SRC = read("api/services/visit-geo.ts");

describe("разбор дня", () => {
  it("зона и минимум визита — общие с анти-фродом", () => {
    /*
      Своя копия пятисот метров означала бы, что визит, признанный
      подозрительным анти-фродом, на экране «как прошёл день» выглядит
      безупречным. Спорить об этом было бы нечем.
    */
    expect(SRC).toContain('from "./anti-fraud"');
    expect(SRC).toContain("GEOFENCE_RADIUS");
    expect(SRC).toContain("MIN_VISIT_DURATION");
    expect(read("api/services/anti-fraud.ts")).toContain("export const GEOFENCE_RADIUS");
  });

  it("расстояние берётся из общей формулы", () => {
    // В anti-fraud своя копия haversine уже завелась однажды; третьей не будет.
    expect(SRC).toContain('from "@contracts/geo"');
    expect(SRC).not.toMatch(/function haversine/);
  });

  it("время точки — когда её сняло устройство", () => {
    /*
      Точки, пролежавшие в буфере без связи, приезжают пачкой с одним
      created_at. Считай мы по нему — весь бессвязный участок схлопнулся бы в
      минуту, а пробег за него стал бы мгновенным прыжком через полгорода.
    */
    expect(SRC).toContain("p.recordedAt ?? p.createdAt");
  });

  it("пробег отсутствует, а не равен нулю, когда точек нет", () => {
    // Ноль означал бы «стоял на месте»; на деле мы просто не знаем.
    expect(SRC).toContain("pathLengthKm(");
    expect(read("contracts/geo.ts")).toContain("points.length < 2) return null");
  });

  it("магазин без координат называется, а не молчит", () => {
    // «Замечаний нет» тогда означало бы «мы не смотрели».
    expect(SRC).toContain("не заполнены координаты");
  });

  it("экран подключён и зовёт ручку", () => {
    /*
      Ровно то, на чём этот продукт спотыкается раз за разом: служба написана,
      ручка написана, вызова нет. Разбор дня раскрывается кнопкой в группе
      агента на вкладке «День» — там же, где видно, что он сам отметил.
    */
    const page = read("src/pages/SupervisorPlans.tsx");
    expect(page).toContain("<GeoDay");
    expect(read("src/components/plans/GeoDay.tsx")).toContain("trpc.geo.day.useQuery");
  });

  it("день раскрывается по одному агенту", () => {
    // Разбор — это чтение всех координат человека за сутки; раскрыть сразу
    // десяток значит десять таких запросов на открытие страницы.
    const page = read("src/pages/SupervisorPlans.tsx");
    expect(page).toContain("geoAgent === group.agentId");
  });

  it("ручка закрыта по организации", () => {
    const ROUTER = read("api/geo-router.ts");
    expect(ROUTER).toMatch(/^ {2}day: supervisorQuery/m);
    expect(ROUTER).toContain("eq(users.tenantId, ctx.tenant.id)");
  });
});
