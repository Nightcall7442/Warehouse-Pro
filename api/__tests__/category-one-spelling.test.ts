/**
 * У категории одно написание, а у товара — один код.
 *
 * ── Что было ────────────────────────────────────────────────────────────────
 *
 * Шестого сентября боевая подняла долю пятисоток выше порога. В журнале лежала
 * цепочка «Duplicate entry 'A61-14' for key 'products.uq_product_code_tenant'»,
 * повторённая подряд, а у арендатора Fresh к этому моменту накопились
 * дубликаты и в товарах, и в категориях.
 *
 * Причин было две, и обе — расхождение путей записи.
 *
 *   1. Категория хранится свободной строкой в products.category, а список
 *      собирается через GROUP BY. Карточка товара чистила строку через
 *      sanitizeString, а обмен с 1С и загрузка из Excel клали её как есть — с
 *      пробелами по краям, которых в выгрузке полно. «Напитки», «напитки » и
 *      « Напитки» становились тремя категориями.
 *
 *   2. Обмен с 1С заводил товар и его связь с 1С тремя отдельными запросами.
 *      Обрыв между ними оставлял товар БЕЗ записи в id_mappings — следующий
 *      обмен не находил его по Ref_Key и вставлял заново, упираясь в
 *      уникальный индекс. Каждый прогон давал ту же ошибку.
 *
 * Здесь проверяется приведение написаний. Атомарность вставки проверяется
 * отдельно, в тестах обмена.
 */
import { describe, it, expect } from "vitest";
import { normalizeCategory, sameCategory, existingSpelling } from "../lib/category";

describe("написание категории", () => {
  it("края и двойные пробелы срезаются", () => {
    // Ровно то, что приходит в выгрузке из 1С и в файлах Excel.
    expect(normalizeCategory("  Напитки  ")).toBe("Напитки");
    expect(normalizeCategory("Бытовая  химия")).toBe("Бытовая химия");
  });

  it("пустое значение — это отсутствие категории, а не пустая категория", () => {
    expect(normalizeCategory("   ")).toBeNull();
    expect(normalizeCategory("")).toBeNull();
    expect(normalizeCategory(null)).toBeNull();
    expect(normalizeCategory(undefined)).toBeNull();
  });
});

describe("одна и та же категория, написанная по-разному", () => {
  it("различие в регистре и пробелах — это одна категория", () => {
    expect(sameCategory("Напитки", "напитки")).toBe(true);
    expect(sameCategory("Напитки", " НАПИТКИ ")).toBe(true);
    expect(sameCategory("Бытовая химия", "Бытовая  химия")).toBe(true);
  });

  it("разные слова — разные категории", () => {
    expect(sameCategory("Напитки", "Напиток")).toBe(false);
    expect(sameCategory("Вода", "Соки")).toBe(false);
  });

  it("отсутствие категории равно отсутствию", () => {
    expect(sameCategory(null, "  ")).toBe(true);
    expect(sameCategory(null, "Напитки")).toBe(false);
  });
});

describe("принятое написание побеждает присланное", () => {
  const known = ["Напитки", "Бытовая химия", null];

  it("выгрузка с другим регистром не заводит вторую категорию", () => {
    expect(existingSpelling("НАПИТКИ", known)).toBe("Напитки");
    expect(existingSpelling(" напитки ", known)).toBe("Напитки");
  });

  it("новая категория пишется так, как её прислали", () => {
    expect(existingSpelling("  Молочное  ", known)).toBe("Молочное");
  });

  it("пустая категория остаётся отсутствием", () => {
    expect(existingSpelling("   ", known)).toBeNull();
  });
});
