import { describe, it, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";
import { salesByProduct, commissionOf, overridesUsed } from "../services/commission-base";

/**
 * Проценты по товарам: комиссия перестала быть одним числом на всё.
 *
 * ── Жалоба, из которой это выросло ──────────────────────────────────────────
 *
 * «Система процентов для агентов неправильная, потому что он поставил разные
 * проценты для разных товаров». Процент был один на человека и на всё, что
 * тот продал, — а торгуют товарами с разной наценкой.
 *
 * ── Что здесь проверяется числами, а не текстом ─────────────────────────────
 *
 * Это деньги, которые человек получает на руки, поэтому проверки считают
 * настоящие суммы, а не ищут слова в исходнике. Главных свойств три:
 *
 *   1. без единой ставки по товарам расчёт даёт РОВНО прежнее число;
 *   2. сумма разложенных частей равна показанной сумме продаж;
 *   3. возврат вычитается ИЗ СВОЕГО товара, а не размазывается по всем.
 *
 * Третье — самое дорогое: при размазывании агент, у которого вернулся дешёвый
 * по проценту товар, недосчитывался бы сорока процентов комиссии.
 */

/**
 * База под `salesByProduct`: два запроса подряд, оба заканчиваются groupBy.
 *
 * Настоящий построитель здесь не нужен — проверяется арифметика разложения, а
 * не то, как drizzle собирает SQL (за этим следят соседние проверки по
 * исходнику). Порядок жёсткий: сперва проданное, потом вернувшееся; их
 * перепутать нельзя, и вторая заглушка отдаёт именно возвраты.
 */
function fakeDb(sold: Array<{ productId: number; amount: string }>,
                returned: Array<{ productId: number; amount: string }>) {
  let call = 0;
  const chain = () => {
    const rows = call++ === 0 ? sold : returned;
    const self: Record<string, unknown> = {};
    self.from = () => self;
    self.innerJoin = () => self;
    self.where = () => self;
    self.groupBy = () => Promise.resolve(rows);
    return self;
  };
  return { select: () => chain() } as any;
}

const P = (id: number, amount: number) => ({ productId: id, amount: amount.toFixed(2) });
const FROM = new Date("2026-09-01");
const TO = new Date("2026-09-30");

describe("пустой список ставок ничего не меняет", () => {
  it("комиссия — ровно продажи × процент человека", () => {
    /*
      Свойство важнее удобства: включение раздела не должно менять зарплату
      людям, которым ничего не меняли. «Почти столько же» здесь не годится —
      человек сравнивает с прошлой ведомостью до копейки.
    */
    expect(commissionOf(new Map(), new Map(), 5, 10_000_000)).toBe(500_000);
    expect(commissionOf(new Map(), new Map(), 3.5, 7_412_300)).toBe(259_430.5);
  });

  it("и когда разложение есть, но ставок по товарам нет", () => {
    // Товар без своей ставки считается процентом человека — значит, сумма
    // частей даёт то же самое, что и умножение целиком.
    const byProduct = new Map([[1, 6_000_000], [2, 4_000_000]]);
    expect(commissionOf(byProduct, new Map(), 5, 10_000_000)).toBe(500_000);
  });
});

describe("разложение сходится с показанной суммой продаж", () => {
  it("скидка на заказ размазывается по товарам", async () => {
    /*
      Скидка живёт на заказе целиком, а не на позициях: строки дают 10 млн, а
      продажами считается 9 млн. Разложить скидку точнее нечем, поэтому она
      делится пропорционально проданному — и сумма частей обязана сойтись с
      тем числом, которое человек видит на экране рядом.
    */
    const by = await salesByProduct(
      fakeDb([P(1, 6_000_000), P(2, 4_000_000)], []),
      1, 7, FROM, TO, 9_000_000,
    );
    expect(by.get(1)).toBeCloseTo(5_400_000, 2);
    expect(by.get(2)).toBeCloseTo(3_600_000, 2);
    expect([...by.values()].reduce((s, v) => s + v, 0)).toBeCloseTo(9_000_000, 2);
  });

  it("продаж нет — раскладывать нечего", async () => {
    const by = await salesByProduct(fakeDb([], []), 1, 7, FROM, TO, 0);
    expect(by.size).toBe(0);
    // И вызывающий считает по проценту человека от нуля, то есть ноль.
    expect(commissionOf(by, new Map([[1, 20]]), 5, 0)).toBe(0);
  });
});

describe("возврат вычитается из своего товара", () => {
  it("вернувшийся дешёвый товар не съедает комиссию с дорогого", async () => {
    /*
      Разбор, ради которого написан весь этот файл.

      Агент продал на 10 млн товара со ставкой 10% и на 10 млн со ставкой 2%.
      Второй вернулся весь, продажами осталось 10 млн.

      Правильный ответ — миллион: вернулся дешёвый по проценту товар, дорогой
      остался.

      Размажь мы возврат пропорционально продажам, вышло бы по 5 млн на
      каждый: 5 × 10% + 5 × 2% = 600 тысяч. Человек недосчитался бы 40%, и
      объяснить ему это было бы нечем.
    */
    const by = await salesByProduct(
      fakeDb([P(1, 10_000_000), P(2, 10_000_000)], [P(2, 10_000_000)]),
      1, 7, FROM, TO, 10_000_000,
    );

    expect(by.get(1)).toBeCloseTo(10_000_000, 2);
    expect(by.has(2), "вернувшийся целиком товар остался в базе комиссии").toBe(false);

    const rates = new Map([[1, 10], [2, 2]]);
    expect(commissionOf(by, rates, 5, 10_000_000)).toBe(1_000_000);
    expect(commissionOf(by, rates, 5, 10_000_000)).not.toBe(600_000);
  });

  it("возврат больше продажи не уезжает вычетом в соседний товар", async () => {
    /*
      Так бывает штатно: продали в прошлом месяце, вернули в этом. Уйди
      разница в минус, она вычлась бы из соседнего товара — с другой ставкой,
      то есть превратилась бы в чужие деньги.
    */
    const by = await salesByProduct(
      fakeDb([P(1, 1_000_000), P(2, 9_000_000)], [P(1, 3_000_000)]),
      1, 7, FROM, TO, 7_000_000,
    );
    expect(by.has(1)).toBe(false);
    expect(by.get(2)).toBeCloseTo(7_000_000, 2);
  });
});

describe("ставка товара и ставка человека", () => {
  const by = new Map([[1, 5_000_000], [2, 5_000_000]]);

  it("товар со своей ставкой считается по ней, остальные — по проценту человека", () => {
    // 5 млн × 10% = 500 000, плюс 5 млн × 3% = 150 000.
    expect(commissionOf(by, new Map([[1, 10]]), 3, 10_000_000)).toBe(650_000);
  });

  it("ноль по товару — это ноль, а не «нет ставки»", () => {
    /*
      «Убрать ставку» и «поставить 0%» — разные решения владельца, и путать их
      нельзя: первое возвращает товар под общий процент, второе означает «с
      этого товара комиссии нет».
    */
    expect(commissionOf(by, new Map([[1, 0]]), 3, 10_000_000)).toBe(150_000);
  });

  it("экран знает, по скольким товарам процент не общий", () => {
    // Иначе человек видит комиссию, не совпадающую с его же процентом от
    // продаж, и читает это как ошибку расчёта.
    expect(overridesUsed(by, new Map([[1, 10]]))).toBe(1);
    expect(overridesUsed(by, new Map([[1, 10], [2, 4], [999, 7]]))).toBe(2);
    expect(overridesUsed(by, new Map())).toBe(0);
  });
});

/* ═══════════════════════════════════════════════════════════════════════════
   Правила, которые числами не проверить: они про то, ОТКУДА берутся строки.
   ═══════════════════════════════════════════════════════════════════════════ */
const read = (p: string) => fs.readFileSync(path.resolve(process.cwd(), p), "utf8").replace(/\r\n/g, "\n");
const BASE = read("api/services/commission-base.ts");
const KPI = read("api/services/kpi.ts");

describe("откуда берутся продажи и возвраты", () => {
  it("продажи — только те заказы, что считаются выручкой", () => {
    /*
      Тот же отбор, что и у самой выручки. Разойдись он — и множитель молча
      прикрыл бы расхождение, размазав его по товарам: сумма сошлась бы, а
      доли оказались бы не те.
    */
    expect(BASE).toContain("revenueOrderConditions(tenantId)");
    expect(BASE, "доставленное считается не тем количеством").toContain("deliveredQty()");
  });

  it("возвраты — по дате ПРОВЕДЕНИЯ и по агенту заказа", () => {
    const at = BASE.indexOf("const returnedRows");
    expect(at, "запрос возвратов не найден").toBeGreaterThan(0);
    const q = BASE.slice(at, BASE.indexOf("const net", at));
    /*
      ОБЕ границы периода — по дате проведения, и ни одной по дате заказа.
      Проверка на «встречается returns.createdAt» этого не ловит: подмени
      нижнюю границу на orders.createdAt, и слово в запросе всё равно есть —
      страж молчал, а период разъезжался ровно на месяц.
    */
    const bounds = [...q.matchAll(/sql`\$\{(\w+)\.createdAt\}\s*([<>]=)/g)].map(m => [m[1], m[2]]);
    expect(bounds, "границы периода возвратов не найдены").toHaveLength(2);
    expect(bounds.map(b => b[0]), "возвраты берутся не по дате проведения")
      .toEqual(["returns", "returns"]);
    expect(bounds.map(b => b[1]).sort()).toEqual(["<=", ">="]);
    expect(q, "непроведённые возвраты тоже вычитаются").toContain('eq(returns.status, "completed")');
    /*
      Агент — из ЗАКАЗА, а не из документа возврата. Это разные люди: возврат
      мог оформить оператор, а продажу теряет тот, чью продажу вернули.
    */
    expect(q, "возврат списывается не с того человека").toContain("eq(orders.agentId, agentId)");
    expect(q, "возврат по отменённому заказу вычитается второй раз")
      .toContain("revenueOrderConditions(tenantId)");
  });

  it("зарплата зовёт общий расчёт, а не считает процент сама", () => {
    /*
      Пока умножение стояло на месте, ставки по товарам можно было завести и
      не заметить, что комиссия их не видит: число выглядит правдоподобно при
      любом проценте.
    */
    const at = KPI.indexOf("export async function calculateSalary");
    const body = KPI.slice(at, KPI.indexOf("\nfunction calculateCompositeScore", at));
    expect(body, "комиссия снова считается на месте")
      .not.toContain("salesAmount * (commissionRate / 100)");
    expect(body, "разложение по товарам не запрашивается").toContain("commissionOf(byProduct");
  });
});
