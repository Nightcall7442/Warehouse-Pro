/**
 * Скидка: процент от нуля до ста, и обязательно число.
 *
 * Диапазон стерегли обе службы — и создание заказа, и обновление, — но обе
 * одинаково слепы к тому, что числом не является:
 *
 *     Number("abc") = NaN,  NaN < 0 → false,  NaN > 100 → false
 *
 * «abc» проходило обе проверки насквозь, дальше subtotal * (NaN / 100) давало
 * NaN, и в денежную колонку уезжало «NaN». Ни осмысленной ошибки человеку, ни
 * пригодной записи в базе.
 *
 * Проверяется тот же разбор, что стоит на границе ручки: правило одно и для
 * веба, и для мобильного приложения, и для обмена с 1С.
 */
import { describe, it, expect } from "vitest";
import { z } from "zod";

/**
 * Копия правила из api/order-router.ts.
 *
 * Схему оттуда не импортировать: файл поднимает весь роутер, а с ним
 * соединение с базой. Правило же — три строки, и ниже стоит проверка, что
 * копия не разошлась с исходником.
 */
const discountPercent = z.union([z.number(), z.string()])
  .transform(String)
  .refine(v => {
    const n = Number(v);
    return Number.isFinite(n) && n >= 0 && n <= 100;
  }, "Скидка — это процент от 0 до 100");

describe("что скидкой быть может", () => {
  it.each([
    ["0", "без скидки"],
    ["10", "десять процентов"],
    ["12.5", "дробный процент"],
    ["100", "всё бесплатно — граница допустимого"],
    [0, "число, а не строка"],
    [7.25, "дробное число"],
    // Пустое поле — это «скидки нет», а не ошибка. Number("") равен нулю, и
    // отклонять очищенное поле значило бы показывать человеку красное
    // «Скидка — это процент от 0 до 100» ровно тогда, когда он скидку убрал.
    // Первая версия этого теста требовала отказа — требовала зря.
    ["", "очищенное поле — скидки нет"],
    ["   ", "одни пробелы — то же самое"],
  ])("%s — %s", (value) => {
    expect(discountPercent.safeParse(value).success).toBe(true);
  });
});

describe("что скидкой быть не может", () => {
  it.each([
    ["101", "больше ста процентов"],
    ["500", "та самая пятисотка, уводившая итог в минус"],
    ["-1", "отрицательная"],
    [-0.5, "отрицательная дробная"],
  ])("%s — %s", (value) => {
    expect(discountPercent.safeParse(value).success).toBe(false);
  });

  it.each([
    ["abc", "буквы"],
    ["10%", "процент внутри значения"],
    ["1e400", "переполнение — бесконечность"],
    [NaN, "не число как есть"],
    [Infinity, "бесконечность как есть"],
  ])("%s — %s", (value) => {
    // Ровно эти значения проходили обе проверки службы насквозь: NaN не
    // меньше нуля и не больше ста.
    const result = discountPercent.safeParse(value);
    expect(
      result.success,
      `Значение ${String(value)} принято как скидка. Дальше сумма заказа ` +
        "считается как NaN и уезжает в денежную колонку.",
    ).toBe(false);
  });
});

describe("правило на границе и в службах не разошлось", () => {
  const read = async (p: string) => (await import("node:fs")).readFileSync(p, "utf8");

  it("в ручке стоит проверка на конечность числа", async () => {
    const src = await read("api/order-router.ts");
    expect(
      /Number\.isFinite\(n\)\s*&&\s*n\s*>=\s*0\s*&&\s*n\s*<=\s*100/.test(src),
      "Правило на границе изменилось — проверьте, что копия в этом тесте ему соответствует.",
    ).toBe(true);
  });

  it("обе службы отсекают не-число", async () => {
    const src = await read("api/services/order.ts");
    const guards = src.match(/Number\.isFinite\((?:discountPercent|pct)\)/g) ?? [];
    expect(
      guards.length,
      "Второй рубеж в services/order.ts пропал: создание и обновление заказа " +
        "снова пропустят NaN, потому что он не меньше нуля и не больше ста.",
    ).toBe(2);
  });
});
