import { describe, it, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";
import { dayKey, monthRange } from "../lib/period";

/**
 * Ключ месяца считается одним способом.
 *
 * ── Что было ────────────────────────────────────────────────────────────────
 *
 * «Первое число текущего месяца» вычислялось двумя разными способами:
 *
 *     ymd(new Date(y, m, 1))                          → «2026-09-01»
 *     new Date(y, m, 1).toISOString().split("T")[0]   → «2026-08-31»
 *
 * Второй берёт МЕСТНУЮ полночь и печатает её в UTC. Пока сервер живёт в UTC,
 * строки совпадают и расхождения не видно. Но TZ не закреплён нигде — ни в
 * Dockerfile, ни в railway.json, — а Ташкент (+5) для этой организации самый
 * естественный выбор: поставь его кто-нибудь, и половина кода станет отвечать
 * «31 августа» на вопрос «какое первое число сентября».
 *
 * Цена — деньги. kpi.setSalary заводил план на «2026-09-01», а myQuota искал
 * «2026-08-31» и отвечал агенту «плана нет»; норма с экрана начальника и норма,
 * которую ищет экран агента, становились двумя строками за один месяц. У
 * комиссий то же самое: ставка и расчёт зарплаты пишут в одну строку, и
 * разъехавшийся на день ключ означал бы две оплаченные комиссии за месяц.
 *
 * Отдельно обидно, что рядом с обоими местами УЖЕ стоял комментарий про этот
 * самый сдвиг. Опасность знали и всё равно печатали дату через UTC.
 */
describe("ключ периода", () => {
  it("собирается по календарю, а не по смещению UTC", () => {
    /*
      Проверка независима от часового пояса машины: берём местную полночь
      первого числа и требуем, чтобы ключ назвал именно это число. При TZ=UTC
      сходятся оба способа, при любом восточном — только правильный.
    */
    const localMidnight = new Date(2026, 8, 1); // 1 сентября 2026, местное
    expect(dayKey(localMidnight)).toBe("2026-09-01");
  });

  it("границы месяца — первое и последнее число", () => {
    expect(monthRange(new Date(2026, 8, 15))).toEqual({ start: "2026-09-01", end: "2026-09-30" });
    expect(monthRange(new Date(2026, 0, 31))).toEqual({ start: "2026-01-01", end: "2026-01-31" });
    // Февраль високосного считается сам, без таблицы длин.
    expect(monthRange(new Date(2028, 1, 10)).end).toBe("2028-02-29");
    expect(monthRange(new Date(2026, 1, 10)).end).toBe("2026-02-28");
  });

  it("декабрь не уводит в следующий год", () => {
    expect(monthRange(new Date(2026, 11, 20))).toEqual({ start: "2026-12-01", end: "2026-12-31" });
  });
});

// ── Разбор исходников ────────────────────────────────────────────────────────
const ROOT = process.cwd();
const read = (p: string) => fs.readFileSync(path.resolve(ROOT, p), "utf8").replace(/\r\n/g, "\n");

/**
 * Файлы, которые ищут и создают строки за период: commissions и sales_targets.
 * Именно здесь разъехавшийся ключ превращается во вторую строку за тот же
 * месяц — то есть в деньги.
 */
const PERIOD_WRITERS = [
  "api/commission-router.ts",
  "api/kpi-router.ts",
  "api/sales-target-router.ts",
  "api/returns-router.ts",
  "api/services/kpi.ts",
];

describe("ключ периода нигде не считается заново", () => {
  it("все места берут его из lib/period", () => {
    const missing = PERIOD_WRITERS.filter(f => !/from "\.\.?\/(lib\/)?period"/.test(read(f)));
    expect(missing, `свой счёт периода вместо общего: ${missing.join(", ")}`).toEqual([]);
  });

  it("дату здесь не печатают через UTC вовсе", () => {
    /*
      Правило нарочно грубое: в этих пяти файлах toISOString не встречается
      НИГДЕ, кроме одного названного помощника.

      Тонкое правило я уже писал и проверял — регулярка ловила «конструктор с
      календарными полями, из которого берут toISOString», и на нарочно
      сломанном коде промолчала: скобки внутри `now.getMonth()` рвали шаблон.
      Проверка показывала ноль находок не потому, что код чист, а потому что не
      умела искать. Такой страж хуже отсутствующего: он успокаивает.

      Исключение одно и названо здесь: toIsoDay превращает в строку то, что
      ОТДАЛА база. Там дата уже пришла в UTC, местной полуночи в ней нет, и
      печатать её так законно.
    */
    const ALLOWED_IN = "function toIsoDay";
    const offenders: string[] = [];
    for (const f of PERIOD_WRITERS) {
      const src = read(f).replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/.*$/gm, "");
      const lines = src.split("\n");
      const helperAt = lines.findIndex(l => l.includes(ALLOWED_IN));
      lines.forEach((line, i) => {
        if (!line.includes(".toISOString()")) return;
        // Тело названного помощника — три строки от его объявления.
        if (helperAt >= 0 && i > helperAt && i <= helperAt + 3) return;
        offenders.push(`${f}:${i + 1}: ${line.trim().slice(0, 90)}`);
      });
    }
    expect(offenders, `дата печатается через UTC там, где ключ периода:\n${offenders.join("\n")}`).toEqual([]);
  });

  it("своих копий ymd не осталось", () => {
    // Копия арифметики считает правильно ровно до первой правки в одной из них.
    const copies = PERIOD_WRITERS.filter(f => /function ymd\s*\(/.test(read(f)));
    expect(copies, `вернулась своя копия ключа: ${copies.join(", ")}`).toEqual([]);
  });
});
