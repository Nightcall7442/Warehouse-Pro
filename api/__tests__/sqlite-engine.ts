/**
 * Движок-двойник для проверок, где считает сам SQL.
 *
 * ── Что тут произошло ───────────────────────────────────────────────────────
 *
 * node:sqlite появился в Node 22.5. Пока приложение собиралось на
 * node:20-alpine, три набора проверок — нумерация заказов, завышение выручки
 * при джойне, пересчёт долга — падали в CI с «No such built-in module» и не
 * выполнялись НИ РАЗУ. Локально, на более новом Node, они проходили и выглядели
 * работающими.
 *
 * Теперь проект требует Node 22.5 и выше: это записано в package.json,
 * в Dockerfile и во всех потоках CI. Проверки выполняются везде, пропускать их
 * больше незачем.
 *
 * ── Зачем файл остался ──────────────────────────────────────────────────────
 *
 * Ради понятного сообщения. Если кто-то запустит набор на более старом Node,
 * он увидит требование и причину, а не «No such built-in module: node:sqlite»
 * посреди списка упавших тестов. Разница между «нужна версия новее» и «что-то
 * сломалось» — это полчаса чужого времени.
 */

const [major, minor] = process.versions.node.split(".").map(Number);

/** Есть ли в этой версии Node встроенный SQLite. */
export const hasSqlite = major > 22 || (major === 22 && minor >= 5);

if (!hasSqlite) {
  throw new Error(
    [
      `Нужен Node 22.5 или новее, здесь ${process.versions.node}.`,
      "Встроенного node:sqlite в этой версии нет, а на нём держатся проверки",
      "нумерации заказов, завышения выручки при джойне и пересчёта долга.",
      "Требование записано в package.json (engines) и в Dockerfile.",
    ].join(" "),
  );
}
