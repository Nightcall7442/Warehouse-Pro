/**
 * Движок-двойник для проверок, где считает сам SQL.
 *
 * ── Почему это отдельный файл ───────────────────────────────────────────────
 *
 * node:sqlite появился в Node 22.5. Приложение собирается на node:20-alpine, и
 * CI ставит Node 20 — там этого модуля нет. Три набора проверок (нумерация
 * заказов, завышение выручки при джойне, пересчёт долга) падали в CI с «No such
 * built-in module: node:sqlite» и не выполнялись НИ РАЗУ. Локально, на Node 24,
 * они проходили и выглядели работающими.
 *
 * Это денежные проверки: одна ловит выручку, завышенную размножением строк при
 * джойне, другая — расхождение в долге магазина. Терять их нельзя.
 *
 * ── Что тут сделано ─────────────────────────────────────────────────────────
 *
 * Пока приложение живёт на Node 20, эти проверки на нём пропускаются — но
 * ГРОМКО, строкой в выводе. Молчаливый пропуск неотличим от прохождения, и
 * через месяц никто не помнит, что они вообще есть.
 *
 * Правильное решение — поднять Node до 22: двадцатый вышел из поддержки
 * 30 апреля 2026 года, то есть приложение работает на версии без обновлений
 * безопасности. Это решение про боевую среду, поэтому оно за владельцем.
 */

const [major, minor] = process.versions.node.split(".").map(Number);
export const hasSqlite = major > 22 || (major === 22 && minor >= 5);

if (!hasSqlite) {
  // stderr напрямую, а не console.warn: vitest перехватывает console на уровне
  // модуля и в итоговый вывод его не пускает — предупреждение пропадало, и
  // пропуск снова становился молчаливым.
  process.stderr.write(
    [
      "",
      "[ПРОПУЩЕНО] Проверки на движке-двойнике не выполняются:",
      `            node:sqlite есть с Node 22.5, здесь Node ${process.versions.node}.`,
      "            Это нумерация заказов, завышение выручки при джойне и пересчёт долга.",
      "            Поднимите Node до 22 — двадцатый снят с поддержки 30.04.2026.",
      "",
      "",
    ].join("\n"),
  );
}

/** Открыть базу в памяти и выполнить проверку. */
export async function withSqlite(
  schema: string,
  fn: (run: (sql: string) => Record<string, unknown>[]) => void,
): Promise<void> {
  const { DatabaseSync } = await import("node:sqlite");
  const db = new DatabaseSync(":memory:");
  const run = (sql: string) => db.prepare(sql).all() as Record<string, unknown>[];
  db.exec(schema);
  try {
    fn(run);
  } finally {
    db.close();
  }
}
