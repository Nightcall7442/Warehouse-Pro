/**
 * Логотип помещается в свой столбец — и знают об этом все, кто его пишет.
 *
 * ── Что случилось ───────────────────────────────────────────────────────────
 *
 * Арендатор загружал логотип во вкладке «Компания» и получал «Внутренняя
 * ошибка сервера». В журнале стоял отклонённый UPDATE settings со всеми
 * реквизитами разом: название, адрес, телефон, ИНН, директор, банк, счёт,
 * МФО — и строка логотипа длиной в сотни тысяч знаков. Не сохранялось НИЧЕГО
 * из перечисленного: MySQL отклоняет запрос целиком, а не обрезает поле.
 *
 * Причина — разошедшиеся числа. Столбцы logo_url объявлены как TEXT, это
 * 65 535 байт. Окно «Брендинг» про это знало и жало картинку до 60 000
 * знаков; окно «Компания» звало то же сжатие общей меркой — до ~685 000, —
 * и клало результат в такой же по устройству столбец.
 *
 * ── Почему тест такой ───────────────────────────────────────────────────────
 *
 * Проверять «сохранилось ли изображение» здесь бессмысленно: сжатие живёт в
 * холсте браузера, которого в этих тестах нет. Ломалось же не сжатие, а
 * СОГЛАСИЕ ЧИСЕЛ — клиент считал предел одним, сервер другим, а столбец
 * третьим. Тест держит именно это согласие и сработает, если завтра кто-то
 * поднимет качество логотипа, не заглянув в объявление столбца.
 */
import { describe, it, expect } from "vitest";
import { LOGO_MAX_CHARS, FAVICON_MAX_CHARS, TEXT_COLUMN_BYTES } from "../lib/image-limits";
import { LOGO_LIMITS, FAVICON_LIMITS } from "../../src/lib/compress-image";

describe("предел логотипа", () => {
  it("серверный предел меньше ёмкости столбца", () => {
    /*
      Не «меньше или равно»: строка data:… это ASCII, знак в байт, и место
      под неё должно оставаться с запасом — столбец хранит ровно то, что
      пришло, без каких-либо заголовков, но упереться в границу впритык
      значит зависеть от того, чего мы не считали.
    */
    expect(LOGO_MAX_CHARS).toBeLessThan(TEXT_COLUMN_BYTES);
    expect(FAVICON_MAX_CHARS).toBeLessThan(TEXT_COLUMN_BYTES);
  });

  it("клиент жмёт не крупнее, чем сервер готов принять", () => {
    // Ровно то, что разошлось: во вкладке «Компания» клиент отдавал больше,
    // чем принимала база.
    expect(LOGO_LIMITS.maxChars).toBeLessThanOrEqual(LOGO_MAX_CHARS);
    expect(FAVICON_LIMITS.maxChars).toBeLessThanOrEqual(FAVICON_MAX_CHARS);
  });

  it("предел задан, а не забыт", () => {
    // Умолчание compressImage рассчитано на фотографию товара (столбец
    // MEDIUMTEXT, 16 МБ) и для логотипа велико на порядок. Отсутствие числа
    // здесь означает, что кто-то снова положился на умолчание.
    expect(LOGO_LIMITS.maxChars).toBeGreaterThan(0);
    expect(FAVICON_LIMITS.maxChars).toBeGreaterThan(0);
  });
});
