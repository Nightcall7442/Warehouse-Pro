import { describe, it, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";

/**
 * Остаток показывается со склада по умолчанию — с того же, откуда спишется
 * заказ.
 *
 * Решение владельца, принято осознанно: продают всегда с основного склада,
 * остальные нужны для хранения и перемещений. Заказ это правило соблюдает
 * жёстко — resolveOrderWarehouse отвергает даже явную попытку указать другой
 * склад. Значит, и каталог обязан показывать остаток ТОГО ЖЕ склада: иначе
 * агент увидит одно число, а сервер решит по другому, и отказ придёт уже
 * после разговора с магазином.
 *
 * Сумму по всем складам показывать нельзя ровно поэтому: агент увидел бы 100,
 * а заказ отклонился, потому что на основном ноль.
 *
 * Отдельно стерегём запасную ветку. Она соединяла строки склада по одному
 * товару, без оглядки на склад: у арендатора с двумя складами это давало ДВЕ
 * строки на товар — товары в каталоге двоились, — и остаток брался с того
 * склада, который подвернулся первым. В данных такой арендатор есть.
 */
const read = (p: string) => fs.readFileSync(path.resolve(process.cwd(), p), "utf8");
const ROUTER = read("api/product-router.ts");
const ORDER = read("api/services/order.ts");

describe("остатки и склад по умолчанию", () => {
  it("каталог берёт остаток со склада по умолчанию", () => {
    expect(ROUTER).toContain("getDefaultWarehouseId");
    // Ровно два места чтения списка (listAll и list) плюс карточка товара.
    const scoped = ROUTER.match(/eq\(warehouseStock\.warehouseId, warehouseId \?\? 0\)/g) ?? [];
    expect(scoped.length, "не все чтения привязаны к складу по умолчанию").toBeGreaterThanOrEqual(3);
  });

  it("чтение без склада по умолчанию не берёт остаток «ниоткуда»", () => {
    /*
      Запасная ветка осталась только у удаления — там обход всех складов нужен
      по делу: строки склада держат товар внешним ключом, и не убрав их
      отовсюду, товар не удалить.
    */
    const loose = ROUTER.match(/: and\(eq\(warehouseStock\.productId,[^)]*\), eq\(warehouseStock\.tenantId, tenantId\)\)/g) ?? [];
    for (const m of loose) {
      const at = ROUTER.indexOf(m);
      const context = ROUTER.slice(Math.max(0, at - 400), at);
      expect(context, `соединение без склада вне удаления: ${m}`).toMatch(/delete|Delete/);
    }
  });

  it("заказ по-прежнему списывает только со склада по умолчанию", () => {
    // Если это правило смягчат, каталог начнёт показывать не тот склад —
    // и разойдётся с тем, что проверяет сервер.
    expect(ORDER).toContain("Заказ можно оформить только со склада по умолчанию");
    expect(ORDER).toContain("Склад по умолчанию не найден");
  });
});
