import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Песочница для интеграторов.
 *
 * ── Что она такое ───────────────────────────────────────────────────────────
 *
 * Отдельная организация с выдуманными данными, на которой чужая сторона
 * проверяет выгрузку: три страницы листания, снимок, отказы 401/403/429. ТЗ
 * BEKDRINKS требует её дважды (пункты 13 и 16-6), а приёмка (17-F) проверяет
 * там же, что запись отвергается и что чужая организация недоступна.
 *
 * ── Чего эти проверки стерегут ──────────────────────────────────────────────
 *
 * Ровно одного: чтобы заполнение выдуманными данными НИКОГДА не смогло
 * коснуться живого арендатора. Ошибка здесь стоит дороже любой другой в этом
 * файле: триста двадцать выдуманных заказов в базе настоящей компании — это
 * испорченная выручка, испорченные долги магазинов и испорченный KPI агентов,
 * и «откатить» это нечем, потому что вперемешку с настоящими они неотличимы.
 *
 * Поэтому условий два и они независимы: пометка песочницы И пустота. Пометку
 * можно поставить по ошибке; заказы в живой организации есть всегда.
 */
const read = (p: string) => readFileSync(join(process.cwd(), p), "utf8").replace(/\r\n/g, "\n");
const SRC = read("api/services/sandbox.ts");
const ROUTER = read("api/tenant-router.ts");
const PUBLIC = read("api/public-api.ts");

/** Комментарий — не код: упоминание слова не значит, что оно исполняется. */
const strip = (code: string) =>
  code.replace(/\/\*[\s\S]*?\*\//g, " ").replace(/(^|[^:])\/\/.*$/gm, "$1");

const CODE = strip(SRC);

describe("заполнить можно только пустую песочницу", () => {
  it("проверяется пометка песочницы", () => {
    expect(CODE, "пометка песочницы не проверяется").toContain("if (!tenant.isSandbox)");
    expect(CODE, "отказ по чужой организации пропал").toContain('code: "FORBIDDEN"');
  });

  it("проверяется пустота — по заказам, а не по чему-то ещё", () => {
    /*
      Именно по заказам: пустая по товарам организация может быть живой (их
      заводят позже), а вот организация без единого заказа — это заведомо не
      та, где кто-то работает.
    */
    expect(CODE).toContain("COUNT(*)");
    expect(CODE).toContain(".from(orders).where(eq(orders.tenantId, tenantId))");
    expect(CODE, "отказ по непустой организации пропал").toContain('code: "CONFLICT"');
  });

  it("обе проверки стоят ДО первой вставки", () => {
    // Проверка после вставки — это уже испорченные данные и вопрос лишь в
    // том, сколько строк успело лечь.
    const flag = CODE.indexOf("if (!tenant.isSandbox)");
    const empty = CODE.indexOf('code: "CONFLICT"');
    const firstInsert = CODE.indexOf(".insert(");
    expect(flag, "пометка не проверяется").toBeGreaterThan(-1);
    expect(firstInsert, "вставок нет вовсе — проверка пуста").toBeGreaterThan(-1);
    expect(flag, "пометку проверяют после вставки").toBeLessThan(firstInsert);
    expect(empty, "пустоту проверяют после вставки").toBeLessThan(firstInsert);
  });

  it("ничего не удаляет и не переписывает", () => {
    /*
      Заполняется только пустое. Соседний db/seed.ts для этого не годится
      принципиально: он ОЧИЩАЕТ базу целиком, и вызов его отсюда стёр бы всех
      арендаторов разом.
    */
    expect(CODE, "в заполнении появилось удаление").not.toMatch(/\.delete\(/);
    expect(CODE, "в заполнении появилась правка чужих строк").not.toMatch(/\.update\(/);
    // Именно в КОДЕ: разбор выше упоминает db/seed.ts словами, и это не вызов.
    expect(CODE, "заполнение зовёт очистку базы").not.toContain("db/seed");
  });

  it("данные выдуманы, а не скопированы у живого арендатора", () => {
    /*
      Скопировать настоящего было бы проще всего и было бы утечкой: названия
      магазинов, телефоны владельцев и их долги уехали бы третьей стороне под
      видом тестовых.
    */
    expect(CODE, "заполнение читает магазины чужой организации").not.toMatch(/\.from\(shops\)/);
    expect(CODE, "заполнение читает товары чужой организации").not.toMatch(/\.from\(products\)/);
  });
});

describe("песочница воспроизводима", () => {
  it("числа берутся из генератора с постоянным зерном", () => {
    /*
      Math.random дал бы другие суммы при каждом создании — и ожидаемые числа
      на той стороне протухали бы вместе с песочницей, а наши проверки не
      могли бы сверять точные итоги.
    */
    expect(CODE, "вернулась случайность без зерна").not.toContain("Math.random");
    expect(CODE).toContain("const SEED =");
    expect(CODE).toContain("makeRandom(SEED)");
  });

  it("заказов хватает на три страницы", () => {
    // Пункт 17-B: «не меньше трёх страниц». Страница по умолчанию сто строк,
    // потолок двести — значит нужно больше шестисот, чтобы проверка была
    // честной при любом выборе. Триста двадцать хватает на умолчании, и это
    // названо числом, а не оставлено на глаз.
    const m = SRC.match(/SANDBOX_ORDER_COUNT = (\d+)/);
    expect(m, "число заказов песочницы не названо").not.toBeNull();
    expect(Number(m![1]), "трёх страниц по сто не наберётся").toBeGreaterThan(300);
  });

  it("срок доставки стоит не у всех заказов", () => {
    /*
      Главное, что песочница показывает про пункт 17-G: пустое поле законно и
      означает «срок не называли». Заполни его у всех — и получатель написал
      бы разбор просрочек, который развалится на первом же живом заказе без
      обещания.
    */
    expect(CODE).toContain("const hasPromise =");
    expect(CODE).toContain("promisedDeliveryAt = hasPromise");
  });

  it("склад один и основной", () => {
    // Продают в этом продукте только с основного склада (решение владельца);
    // второй склад показывал бы выгрузке то, чего в жизни не бывает.
    expect(CODE).toContain("isDefault: true");
    expect(CODE.match(/\.insert\(warehouses\)/g) ?? [], "складов стало больше одного").toHaveLength(1);
  });
});

describe("песочница называет себя песочницей", () => {
  it("каждый ответ выгрузки помечен средой", () => {
    /*
      Ключ песочницы живёт в настройках у чужой стороны рядом с боевым.
      Перепутать их — это отчёт заказчику по выдуманным заказам, и заметить
      подмену по самим числам нельзя: они выглядят как настоящие.
    */
    expect(PUBLIC).toContain('c.header("X-Warehouse-Environment"');
    expect(PUBLIC).toContain('tenant.isSandbox ? "sandbox" : "production"');
  });

  it("проверка связи сразу говорит, куда попал", () => {
    const at = PUBLIC.indexOf('app.get("/health"');
    expect(at, "проверки связи нет").toBeGreaterThan(-1);
    expect(PUBLIC.slice(at, PUBLIC.indexOf("));", at))).toContain("environment");
  });

  it("ключ песочницы отличается на вид", () => {
    // Технически приставка ни на что не влияет — ключ проверяется отпечатком.
    // Влияет она на человека, который читает конфиг.
    expect(strip(ROUTER)).toContain('"wp_test_"');
  });
});

describe("выгрузка наружу только читает", () => {
  it("небезопасный метод отвергается внятно", () => {
    /*
      Пункт 17-F требует, чтобы в песочнице отвергалась запись. Отвергать её
      нечем: писать через выгрузку нельзя нигде и никому. Но ответ обязан
      сказать это словами, а не «404, такого адреса нет»: иначе получатель
      будет искать опечатку в адресе.
    */
    expect(PUBLIC).toContain('c.req.method !== "GET" && c.req.method !== "HEAD"');
    expect(PUBLIC).toContain("read-only");
    expect(PUBLIC).toContain("405");
  });

  it("записывающих маршрутов не появилось", () => {
    /*
      Храповик: сегодня их ноль, и стать их больше не должно молча. Появится
      POST — станет видно здесь, и решение «а можно ли вообще писать через
      выгрузку» будет принято осознанно.
    */
    const writers = [...strip(PUBLIC).matchAll(/app\.(post|put|patch|delete)\(/g)].map(m => m[1]);
    expect(writers, `в выгрузку добавили запись: ${writers.join(", ")}`).toEqual([]);
  });
});
