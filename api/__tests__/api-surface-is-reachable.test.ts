import { describe, it, expect } from "vitest";
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";

/**
 * Ручка, которую не зовёт никто, — это не запас, это долг.
 *
 * ── Болезнь ─────────────────────────────────────────────────────────────────
 *
 * В этом продукте она ловилась уже шесть раз, и каждый раз по-разному больно:
 *
 *   • ручки погрузочного листа написаны и не позваны — у арендатора ВСТАЛА
 *     сборка: одиннадцать заказов заперлись в листе, который нечем закрыть;
 *   • StockService.reserve/release/deduct — три главные операции склада — не
 *     звал никто, и остаток меняли девятнадцать мест сырым SQL;
 *   • процедуры чтения отчётов о визитах, salesTarget.*, getOptimizedRoute,
 *     returns.summary — написаны, выставлены наружу, мертвы.
 *
 * Общее у всех одно: код ЕСТЬ, он проходит проверки типов, его читают при
 * разборе и считают работающим. Он не работает — он просто есть.
 *
 * ── Почему проверка, а не разовая уборка ────────────────────────────────────
 *
 * Убрать сегодняшние сорок восемь — работа на неделю и на отдельное решение
 * владельца: часть из них это НЕДОДЕЛАННЫЕ фичи (перемещения между складами,
 * управление прайс-листами, прогноз спроса), и выбрасывать их нельзя, их надо
 * ДОДЕЛАТЬ. Что можно сделать сегодня — остановить рост и назвать число.
 *
 * Поэтому храповик: число заморожено, вырасти не может. Дописал ручку — либо
 * позови её с экрана, либо объясни, зачем она нужна, подняв число руками.
 * Подключил старую — число падает, и проверка требует опустить потолок.
 *
 * ── Чего проверка НЕ видит ──────────────────────────────────────────────────
 *
 * Мобильное приложение живёт отдельным репозиторием, и здесь его нет. Ручки,
 * которые зовёт только оно, перечислены поимённо ниже — с указанием, где
 * именно. Если мобилка перестанет звать такую ручку, здесь этого не увидят: за
 * тем списком надо следить руками при правках контракта.
 */

const API_DIR = join(__dirname, "..");
const SRC_DIR = join(API_DIR, "..", "src");
const read = (p: string) => readFileSync(p, "utf8").replace(/\r\n/g, "\n");

/** Пространство имён → файл роутера, как их смонтировал api/router.ts. */
function mountedRouters(): Map<string, string> {
  const src = read(join(API_DIR, "router.ts"));
  const imports = new Map<string, string>();
  for (const m of src.matchAll(/import\s*\{\s*(\w+)\s*\}\s*from\s*"\.\/([\w/-]+)"/g)) {
    imports.set(m[1], m[2]);
  }
  const mounted = new Map<string, string>();
  for (const m of src.matchAll(/^\s*(\w+):\s*(\w+Router),/gm)) {
    const file = imports.get(m[2]);
    if (file) mounted.set(m[1], join(API_DIR, ...file.split("/")) + ".ts");
  }
  return mounted;
}

/** Все ручки: «пространство.имя». */
function allProcedures(): Map<string, string> {
  const out = new Map<string, string>();
  for (const [ns, file] of mountedRouters()) {
    let src: string;
    try { src = read(file); } catch { continue; }
    for (const m of src.matchAll(/^ {2}(\w+):\s*(?:\w+Query|\w+Procedure|publicProcedure|t\.procedure)/gm)) {
      out.set(`${ns}.${m[1]}`, file);
    }
  }
  return out;
}

/**
 * Убрать комментарии.
 *
 * Иначе УПОМИНАНИЕ ручки считается её вызовом. Поймано на себе: я написал в
 * комментарии, что warehouseReports.reorderAlerts зовёт мобилка, — и проверка
 * решила, что её зовут экраны. То есть достаточно было НАПИСАТЬ ПРО мёртвую
 * ручку, чтобы охранник перестал её видеть.
 *
 * Две косые после двоеточия не трогаются: это адрес, а не комментарий.
 */
function stripComments(code: string): string {
  return code
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .replace(/(^|[^:])\/\/.*$/gm, "$1");
}

/** Весь код экранов одной строкой — по нему и ищем вызовы. */
function webSources(): string {
  const parts: string[] = [];
  const walk = (dir: string) => {
    for (const entry of readdirSync(dir)) {
      if (entry === "node_modules") continue;
      const full = join(dir, entry);
      if (statSync(full).isDirectory()) walk(full);
      else if (/\.tsx?$/.test(entry)) parts.push(stripComments(read(full)));
    }
  };
  walk(SRC_DIR);
  return parts.join("\n");
}

/**
 * Ручки, которые зовёт мобильное приложение.
 *
 * Оно живёт отдельным репозиторием (Warehouse-Pro-Mobile), и его исходников
 * здесь нет. Раньше список вёлся руками и ветшал; теперь его порождает
 * scripts/mobile-contract.mjs из src/api.ts мобилки —
 * contracts/mobile-procedures.json. Что в нём есть — зовёт мобилка, и точка.
 */
const MOBILE_ONLY = new Set(
  (JSON.parse(read(join(API_DIR, "..", "contracts", "mobile-procedures.json"))) as Array<{ path: string }>).map(c => c.path),
);

/**
 * Сколько ручек сейчас не зовёт НИКТО — ни экраны, ни мобилка.
 *
 * Число заморожено и опускается по мере того, как ручки подключают или
 * убирают. Выросло — проверка падает и требует объяснить, зачем понадобилась
 * ещё одна мёртвая.
 *
 * 48 → 47: warehouseReports.productBatches подключён к карточке товара. Он
 * появился вместе с учётом партий и был мёртв ровно один вечер — ровно эта
 * проверка его и нашла, в тот же день, когда была написана.
 *
 * 47 → 46: returns.updateStatus. Самая дорогая из мёртвых: это ЕДИНСТВЕННЫЙ
 * способ вывести возврат из «на рассмотрении», и не звал его никто — страницы
 * возвратов в вебе не существовало, мобилка их только заводит. То есть
 * состояние «проведён» было недостижимо через продукт, а на него опираются
 * долг магазина, прибыль, комиссия, доля возвратов в KPI и рейтинг магазина:
 * пять расчётов считали правильно то, чего не бывает.
 *
 * 46 → 43: перемещения между складами (createTransfer, completeTransfer,
 * listTransfers). Сервер умел это давно — с блокировками, проверкой чужих
 * складов и защитой от двойного проведения, — а кнопки не было ни одной.
 * Вкладка «Перемещения» на странице склада.
 *
 * 43 → 36: прайс-листы (create, update, delete, upsertItem, removeItem,
 * assignShop, unassignShop). Мобилка их ЧИТАЕТ давно — агент видит в заказе
 * цену своего магазина, — а завести было нечем. Раздел «Прайс-листы» в
 * настройках.
 *
 * 36 → 32: прогноз спроса (stockoutPrediction, reorderRecommendation,
 * trendingProducts, demandForecast). За ними стояла настоящая служба —
 * скользящее среднее, экспоненциальное сглаживание, линейный тренд, недельная
 * сезонность и выбор лучшего метода по ошибке, — и ни одной кнопки. Вкладка
 * «Прогноз» на странице склада.
 *
 * forecast.categoryTrend остаётся мёртвым сознательно: тренд ОДНОЙ категории
 * отвечает на вопрос, которого никто не задавал — на складе смотрят по
 * товарам, а в аналитике категории уже разложены. Убирать его или дописывать
 * экран — решение владельца, а не моё.
 *
 * 32 → 33, и это не рост: проверка перестала считать вызовом УПОМИНАНИЕ ручки
 * в комментарии. Нашлось на себе — я написал в комментарии, что
 * warehouseReports.reorderAlerts зовёт мобилка, и охранник решил, что её зовут
 * экраны. Разбор комментариев вскрыл ещё двух, которые всё это время считались
 * живыми по той же причине: reports.getAgentPerformance и
 * salesTarget.recalculateActuals. Прежние потолки были оптимистичны на эту
 * пару.
 *
 * 33 → 23: подключено то, что лежало готовым.
 *   commission.updateStatus — утверждение и выплата комиссии. Пересчёт нарочно
 *     не трогает утверждённые строки, но поставить это состояние было нечем, и
 *     каждый пересчёт молча переписывал уже выплаченную сумму;
 *   apiKey.create/list/revoke/setStatus — публичное API существовало, а войти
 *     в него было нечем: ключ выдаётся и показывается один раз;
 *   telegram.testBroadcast / dailyDigest — «дошло или нет» после настройки;
 *   onec.issueWebhookSecret / metrics — в подсказке предлагалось придумать
 *     секрет самому и вписать руками в двух местах;
 *   user.logoutAll — выход на всех устройствах: чужая сессия живёт своим
 *     ключом и переживает смену пароля.
 *
 * 23 → 12. Подключено: sse.recentEvents (догон пропущенного после обрыва —
 * уведомления, пришедшие в те пять секунд, терялись целиком), system.errors
 * (сырой журнал: группы не отвечают на вопрос «что происходило в 14:32»),
 * audit.exportCsv (журнал ведут ради спора, а спорят по бумаге).
 *
 * И УБРАНО семь ручек, отвечавших на вопрос, уже отвечённый другой ручкой:
 *   system.dbHealth, sse.stats     — то же отдаёт system.status;
 *   tenant.current                 — то же приходит с auth.me;
 *   user.getById                   — те же поля есть в user.list;
 *   kpi.supervisorKpi              — то же отдаёт agentList, и групповыми
 *                                    запросами вместо расчёта на каждого;
 *   reports.getAgentPerformance    — analytics.agentPerformance и kpi.agentList;
 *   shop.debtReport                — analytics.debtReport;
 *   forecast.categoryTrend         — вопрос, которого на складе не задают.
 *
 * Две ручки на один ответ — это две правды, которые однажды разойдутся: одну
 * починят, вторую забудут. В этом продукте так уже вышло трижды.
 *
 * 12 → 6: заявки с сайта (lead.list/markHandled — уведомление в телеграм это
 * попытка, а не условие, и заявка сохраняется как раз на случай, когда оно не
 * дошло), приглашения (invite.list — «звал троих, пришёл один»), деньги
 * магазина (shop.getDebtDetails, analytics.shopRevenueTrend — разговор с
 * магазином начинается с «за что?»), список районов (shop.districts — фильтр
 * работал, а выбрать район можно было только вписав название в адрес).
 *
 * 6 → 0. Подключено:
 *   onec.syncOrder — САМАЯ дорогая из оставшихся. Заказы не уезжают в 1С
 *     сами: расписания для них нет, и syncOrderTo1C зовётся ровно из этой
 *     ручки. У организации с настроенным обменом товары приезжали, а заказы
 *     не уходили, и увидеть это можно было только по пустой 1С. Кнопка — в
 *     карточке заказа;
 *   agent.gamification — вместе с ней лежала и целиком написанная карточка,
 *     которую тоже никто не показывал. Отвечает на вопрос, которого не
 *     отвечает ни один живой экран: 4 000 000 за неделю — это первое место в
 *     одной организации и последнее в другой;
 *   audit.purge — журнал только рос: у уведомлений ночная уборка есть, у него
 *     не было ничего. Ночной работой не сделано намеренно — журнал ведут ради
 *     спора, и решение «этих записей больше нет» принимает человек.
 *
 * И убрано:
 *   analytics.cogsSummary  — те же величины отдаёт pnl, но у неё вычтены
 *                            проведённые возвраты, а здесь нет: два ответа на
 *                            один вопрос, и меньший из них правильный;
 *   salesTarget.recalculateActuals — писала снимок в колонки actual_*, который
 *                            никто не читает: list, summary и myQuota считают
 *                            выполнение вживую одним общим счётом;
 *   agent.nearbyShops      — «мои магазины в радиусе N км». Экран «рядом» есть
 *                            только в мобильном, и он берёт agent.myShops, а
 *                            расстояние считает у себя — заодно показывая его
 *                            числом и сортируя по нему.
 *
 * Ноль — не «больше нечего искать», а условие: теперь ЛЮБАЯ новая ручка,
 * оставшаяся без вызова, роняет проверку в тот же день, когда написана.
 */
const BASELINE = 0;

describe("вся поверхность API кем-то вызывается", () => {
  const procedures = allProcedures();
  const web = webSources();

  const unreachable = [...procedures.keys()]
    .filter(key => !web.includes(key))
    .filter(key => !MOBILE_ONLY.has(key))
    .sort();

  it("упоминание в комментарии вызовом не считается", () => {
    /*
      Стража стражи, и она нашлась на живом примере: комментарий, объясняющий,
      что ручку зовёт мобилка, делал эту ручку «вызванной» с экрана.
    */
    expect(stripComments("// trpc.order.list.useQuery()")).not.toContain("order.list");
    expect(stripComments("/* см. trpc.order.list */")).not.toContain("order.list");
    expect(stripComments("const q = trpc.order.list.useQuery();")).toContain("order.list");
    // Адрес — не комментарий.
    expect(stripComments('const url = "https://x.dev/order.list";')).toContain("order.list");
  });

  it("разбор нашёл роутеры и ручки, а не пустоту", () => {
    // Проверка, которая ничего не разобрала, зелена всегда.
    expect(procedures.size, "ручек не найдено — разбор роутера сломан").toBeGreaterThan(200);
    expect(web.length, "исходники экранов не прочитаны").toBeGreaterThan(100_000);
    // Заведомо живая ручка обязана находиться: иначе поиск вызовов не работает.
    expect(web).toContain("order.list");
  });

  it("мёртвых ручек не становится больше", () => {
    const byFile = new Map<string, string[]>();
    for (const key of unreachable) {
      const file = procedures.get(key)!.split(/[\\/]/).slice(-2).join("/");
      byFile.set(file, [...(byFile.get(file) ?? []), key]);
    }
    const report = [...byFile.entries()]
      .map(([file, keys]) => `  ${file}\n${keys.map(k => `      ${k}`).join("\n")}`)
      .join("\n");

    expect(
      unreachable.length,
      unreachable.length <= BASELINE ? "" :
        `Мёртвых ручек стало ${unreachable.length} (было ${BASELINE}):\n${report}\n\n` +
        `Ручка, которую не зовёт ни один экран, не работает — она просто есть.\n` +
        `Так у арендатора встала сборка: ручки закрытия погрузочного листа были\n` +
        `написаны и не позваны, и одиннадцать заказов заперлись без выхода.\n\n` +
        `Позовите её с экрана, уберите — или, если она нужна мобилке, впишите\n` +
        `в contracts/mobile-procedures.json (его порождает scripts/mobile-contract.mjs).`,
    ).toBeLessThanOrEqual(BASELINE);
  });

  it("храповик крутится в одну сторону", () => {
    // Подключили мёртвую — опустите потолок, иначе он перестанет держать.
    expect(
      unreachable.length,
      `Мёртвых ручек стало меньше (${unreachable.length} вместо ${BASELINE}) — ` +
      `опустите BASELINE, чтобы храповик не дал им вернуться.`,
    ).toBe(BASELINE);
  });

  it("список мобильных ручек не покрывает несуществующие", () => {
    /*
      Список именной, и он ветшает: ручку переименовали или убрали, а строка
      осталась — и прикрывает уже другую дыру, потому что имя в множестве
      просто не совпадает ни с чем.
    */
    const stale = [...MOBILE_ONLY].filter(key => !procedures.has(key));
    expect(stale, `в MOBILE_ONLY остались ручки, которых больше нет: ${stale.join(", ")}`).toEqual([]);
  });
});
