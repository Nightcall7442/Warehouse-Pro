import { logger } from "./logger";

/* ═══════════════════════════════════════════════════════════════════════════
   Взаимная блокировка на время применения миграций.

   ── Зачем ──────────────────────────────────────────────────────────────────

   Миграции применяются внутри процесса, при запуске. Пока реплика одна, это
   безупречно. Со второй начинается гонка: при выкладке обе стартуют
   одновременно, обе читают одно и то же состояние журнала миграций и обе
   начинают выполнять один и тот же DDL.

   Проигравшая получает «Table already exists» или «Duplicate column name»,
   а такая ошибка здесь ведёт к немедленному выходу из процесса — и правильно
   ведёт: работать на схеме, которой код не соответствует, дороже. Но выходит
   она не из-за настоящей поломки, а из-за соседа.

   Платформа перезапустит проигравшую, и со второй попытки та увидит миграции
   уже применёнными. То есть само по себе это не смертельно — но каждая
   выкладка тратит одну-две попытки из отведённого числа перезапусков, а при
   неудачном стечении их не остаётся, и выкладка встаёт целиком.

   Redis в проекте уже подключён именно ради нескольких реплик, так что вторая
   — вопрос времени.

   ── Почему замок в самой базе, а не в Redis ────────────────────────────────

   Замок обязан жить там же, где данные, которые он защищает. Redis может быть
   не задан (переменная необязательная), может отстать, может быть общим для
   нескольких сред. База — единственное, что у всех реплик заведомо одно.

   GET_LOCK — именованный замок MySQL. Он привязан к соединению: если процесс
   умрёт посреди миграции, соединение закроется и замок освободится сам. Ждать
   вечно тоже не придётся — время ожидания задано.
   ═══════════════════════════════════════════════════════════════════════════ */

const LOCK_NAME = "warehouse_pro:migrate";

/**
 * Сколько ждать своей очереди.
 *
 * Столько же, сколько может занять самая долгая миграция на большой базе.
 * Не дождались — выходим с ошибкой, и платформа перезапустит: это лучше, чем
 * висеть без объяснений.
 */
const LOCK_TIMEOUT_S = 300;

/** То, что нам нужно от пула mysql2, без привязки к его типам. */
interface PoolLike {
  getConnection(): Promise<ConnectionLike>;
}

interface ConnectionLike {
  query(sql: string, values?: unknown[]): Promise<unknown>;
  release(): void;
}

function firstRowValue(result: unknown): number | null {
  // mysql2 отдаёт [rows, fields]; нам нужна первая ячейка первой строки.
  const rows = Array.isArray(result) ? result[0] : undefined;
  const row = Array.isArray(rows) ? rows[0] : undefined;
  if (!row || typeof row !== "object") return null;
  const value = (row as Record<string, unknown>).ok;
  return value === null || value === undefined ? null : Number(value);
}

/**
 * Выполнить работу, держа общий замок.
 *
 * Замок берётся и отпускается на ОДНОМ соединении: GET_LOCK привязан к
 * соединению, и освободить его с другого нельзя. Сама работа при этом вольна
 * пользоваться пулом как обычно — важно лишь, чтобы замок кто-то держал.
 */
export async function withMigrationLock<T>(pool: PoolLike, run: () => Promise<T>): Promise<T> {
  const conn = await pool.getConnection();

  try {
    const acquired = firstRowValue(
      await conn.query("SELECT GET_LOCK(?, ?) AS ok", [LOCK_NAME, LOCK_TIMEOUT_S]),
    );

    // 1 — взяли, 0 — не дождались, NULL — ошибка на стороне базы.
    if (acquired !== 1) {
      throw new Error(
        acquired === 0
          ? `не дождались очереди на миграции за ${LOCK_TIMEOUT_S} с — другой процесс всё ещё их применяет`
          : "база не смогла выдать замок на миграции",
      );
    }

    logger.info("migration lock acquired");

    try {
      return await run();
    } finally {
      // Отпускаем в любом случае, в том числе после неудачной миграции: иначе
      // соседи будут ждать до истечения времени вместо того, чтобы получить
      // свой отказ сразу.
      await conn.query("SELECT RELEASE_LOCK(?) AS ok", [LOCK_NAME]).catch(() => {});
      logger.info("migration lock released");
    }
  } finally {
    conn.release();
  }
}
