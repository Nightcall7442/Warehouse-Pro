/**
 * Разбор ошибок драйвера базы.
 *
 * ── Почему это отдельный файл, а не `err.code` по месту ─────────────────────
 *
 * Потому что `err.code` по месту перестал работать, и никто не заметил.
 *
 * drizzle заворачивает ошибку драйвера в свою: наружу приезжает
 *
 *     Error: Failed query: insert into `orders` … params: …
 *       Caused by: Error: Duplicate entry '№1-1' for key 'orders.uq_order_number_tenant'
 *
 * У обёртки нет ни `code`, ни `sqlMessage` — они у той ошибки, что лежит в
 * `cause`. Проверки вида `(err as {code?: string}).code === "ER_DUP_ENTRY"`
 * стали давать false ВСЕГДА, а вместе с ними молча отключились:
 *
 *   • повтор с новым номером заказа при коллизии uq_order_number_tenant;
 *   • распознавание дубликата по ключу идемпотентности;
 *   • та же логика для магазинов в agent-router и для оплат.
 *
 * Последствие не теоретическое. Агент возвращается в сеть с пятью
 * накопленными заказами, очередь шлёт их разом, все пять считают один и тот
 * же следующий номер, четверо падают на уникальном индексе — и вместо
 * повтора с номером на единицу больше получают пятисотую. Мобильное
 * приложение помечает записи как неповторяемые, и заказы остаются лежать,
 * пока агент не нажмёт «Повторить» по каждому вручную.
 *
 * Ровно это описано в комментарии к isIdempotencyDuplicate как УЖЕ
 * исправленное. Исправление было верным — его отменило обновление drizzle,
 * потому что оба обработчика читали ошибку с одного уровня.
 *
 * Нашлось это первым же запуском проверок на настоящей MySQL: на заглушке
 * никаких уникальных индексов нет, и обе ветки там недостижимы.
 */

/** Ошибка mysql2 — то, что нас в ней интересует. */
interface DriverError {
  code?: string;
  errno?: number;
  sqlMessage?: string;
  message?: string;
}

/**
 * Ошибка и всё, во что она завёрнута.
 *
 * Глубина ограничена: цепочка `cause` в теории может быть кольцевой, и на
 * разборе ошибки зацикливаться — худшее, что можно сделать.
 */
function chainOf(err: unknown, limit = 5): DriverError[] {
  const chain: DriverError[] = [];
  let current: unknown = err;
  for (let depth = 0; current && typeof current === "object" && depth < limit; depth++) {
    chain.push(current as DriverError);
    current = (current as { cause?: unknown }).cause;
  }
  return chain;
}

/** Нарушен какой-то уникальный индекс — на любом уровне вложенности. */
export function isDuplicateEntry(err: unknown): boolean {
  return chainOf(err).some(e => e.code === "ER_DUP_ENTRY" || e.errno === 1062);
}

/**
 * Нарушен именно этот индекс.
 *
 * Имя драйвер кладёт в текст: «Duplicate entry '…' for key 'orders.uq_…'».
 * У обёртки drizzle текст свой, поэтому смотреть надо всю цепочку.
 *
 * Если имени в сообщении нет (другой драйвер, урезанный текст) — ответ
 * отрицательный, и вызывающий разбирается по своему умолчанию. У заказов оно
 * такое: считать коллизией номера и повторить. Обратное умолчание хуже, оно
 * останавливает офлайн-очередь.
 */
export function isDuplicateOf(err: unknown, indexName: string): boolean {
  return chainOf(err).some(e => (e.sqlMessage ?? e.message ?? "").includes(indexName));
}
