/**
 * Признаки выкладки: то, что происходит из-за неё, а не из-за поломки.
 *
 * ── Зачем отдельный счётчик ─────────────────────────────────────────────────
 *
 * После каждой выкладки вкладки, оставшиеся на прежней сборке, просят свои
 * куски приложения по старым именам с хэшем и получают 404 — десятками подряд.
 * Приложение это умеет чинить само (isStaleChunkError → recoverFromStaleApp),
 * человек ничего не замечает.
 *
 * В журнале ошибок такие строки были ядом: они топили те немногие записи, ради
 * которых журнал и открывают, и поднимали долю ошибок до полутора процентов на
 * совершенно исправной системе.
 *
 * Выбрасывать их совсем тоже неверно: число само по себе полезно — по нему
 * видно, что выкладка прошла и часть людей ещё работает со старым. Поэтому не
 * ошибка, а счётчик.
 *
 * ── Почему отдельный файл ───────────────────────────────────────────────────
 *
 * Считает их промежуточный слой в boot.ts, а показывает system-router. Держать
 * счётчик в boot.ts нельзя: boot импортирует роутер, и обратный импорт замкнул
 * бы круг. Модуль на две строки дешевле такого круга.
 */
let staleAssetHits = 0;

/** Вкладка спросила кусок прежней сборки. */
export function noteStaleAssetHit(): void {
  staleAssetHits++;
}

/** Сколько таких обращений было с запуска. */
export function getStaleAssetHits(): number {
  return staleAssetHits;
}

/** Только для проверок: начать счёт заново. */
export function resetStaleAssetHits(): void {
  staleAssetHits = 0;
}
