/**
 * Снять резервную копию боевой базы, проверить её и убрать старые.
 *
 * ── Зачем ────────────────────────────────────────────────────────────────────
 *
 * На 31 августа 2026 у боевой базы не было ни одной копии и не было задано
 * расписание: вкладка Backups службы MySQL-avuz пуста. Всё накопленное —
 * тринадцать фирм, три тысячи магазинов, полтора года заказов — держалось на
 * одном томе. Дамп при этом снимать было чем: scripts/dump-database.mjs есть и
 * работает. Но запускался он руками, а значит не запускался.
 *
 * Этот скрипт — то, что можно поставить в расписание и забыть.
 *
 * ── Почему отдельно от копий Railway ─────────────────────────────────────────
 *
 * Копии Railway включаются в панели и защищают от неудачной миграции, сбоя тома
 * и ошибочного DELETE. Они НЕ защищают от бед с самой учётной записью: потеря
 * доступа, спор об оплате, ошибка поставщика. Копия, лежащая у того же
 * поставщика, что и база, закрывает часть случаев, а не все. Поэтому вторая,
 * снаружи, — и одно другое не заменяет.
 *
 * ── Запуск ───────────────────────────────────────────────────────────────────
 *
 *     railway run --service MySQL-avuz node scripts/backup-database.mjs
 *
 * Строку подключения подставляет Railway; в скрипте, в расписании и на диске её
 * нет. Пароль нигде не хранится — этим `railway run` и хорош.
 *
 * Куда складывать — переменная BACKUP_DIR, по умолчанию каталог
 * WarehousePro-backups в домашней папке. Сколько копий держать — BACKUP_KEEP,
 * по умолчанию четырнадцать.
 */

import { spawn } from "node:child_process";
import { createReadStream, createWriteStream } from "node:fs";
import { mkdir, readdir, rm, stat, appendFile } from "node:fs/promises";
import { createGzip } from "node:zlib";
import { pipeline } from "node:stream/promises";
import { homedir } from "node:os";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const здесь = dirname(fileURLToPath(import.meta.url));
const корень = resolve(здесь, "..");

const ПЕРЕМЕННЫЕ = ["MYSQL_PUBLIC_URL", "DATABASE_PUBLIC_URL", "MYSQL_URL", "DATABASE_URL"];
const имяПеременной = ПЕРЕМЕННЫЕ.find(k => process.env[k]);

if (!имяПеременной) {
  console.error("Не нашёл строку подключения. Искал:", ПЕРЕМЕННЫЕ.join(", "));
  console.error("Запускать через: railway run --service MySQL-avuz node scripts/backup-database.mjs");
  process.exit(1);
}

const каталог = resolve(process.env.BACKUP_DIR || join(homedir(), "WarehousePro-backups"));
const хранить = Number(process.env.BACKUP_KEEP || 14);

/**
 * Копия НЕ должна попасть внутрь репозитория.
 *
 * Репозиторий открыт всем, и дамп, случайно оказавшийся внутри и попавший в
 * коммит, — это публикация базы клиентов. Восстановить такое нельзя: чужие
 * копии истории уже разойдутся. Проверка стоит здесь, а не в напоминании в
 * документации, потому что напоминание можно не прочитать.
 */
if (каталог === корень || каталог.startsWith(корень + "\\") || каталог.startsWith(корень + "/")) {
  console.error(`BACKUP_DIR указывает внутрь репозитория (${каталог}).`);
  console.error("Репозиторий открыт всем — дамп там оказаться не должен. Укажите путь вне него.");
  process.exit(1);
}

const метка = new Date().toISOString().replace(/[:.]/g, "-").slice(0, 19);
await mkdir(каталог, { recursive: true });

const сырой = join(каталог, `warehouse-pro-${метка}.sql`);
const сжатый = `${сырой}.gz`;

// ── 1. Снять дамп ────────────────────────────────────────────────────────────
// Существующим скриптом, а не своей копией его логики: он уже умеет потоковую
// выгрузку, экранирование и разбиение на пакеты по размеру.
console.log(`Снимаю дамп по переменной ${имяПеременной}…`);

const код = await new Promise((готово, сбой) => {
  const п = spawn(
    process.execPath,
    [join(здесь, "dump-database.mjs"), process.env[имяПеременной], сырой],
    { stdio: ["ignore", "inherit", "inherit"] },
  );
  п.on("error", сбой);
  п.on("close", готово);
});

if (код !== 0) {
  console.error(`\nДамп не снялся, код ${код}. Копия не создана.`);
  await rm(сырой, { force: true });
  process.exit(1);
}

// ── 2. Проверить, что это похоже на восстановимый дамп ───────────────────────
//
// Пустой или обрезанный файл выглядит как копия и успокаивает ровно до того
// дня, когда из него надо восстановиться. Дешевле убедиться сейчас.
//
// Читается ВЕСЬ файл, потоком. Первая версия проверки смотрела только первые
// 200 КБ и насчитала в них две таблицы из сорока шести: дамп чередует
// определения с многомегабайтными вставками, и в начало попадает лишь пара
// первых. Проверка ругалась на здоровый дамп — то есть была бы отключена при
// первом же ложном срабатывании, а вместе с ней и настоящая.
//
// Главный признак целостности — завершающая строка. Она пишется последней,
// поэтому её наличие означает, что выгрузка дошла до конца, а не оборвалась.
const размер = (await stat(сырой)).size;

let таблиц = 0;
let заголовок = false;
let хвост = "";
let остаток = "";

for await (const кусок of createReadStream(сырой, { encoding: "utf8", highWaterMark: 1 << 20 })) {
  const текст = остаток + кусок;
  таблиц += (текст.match(/CREATE TABLE/g) ?? []).length;
  if (!заголовок && текст.includes("SET FOREIGN_KEY_CHECKS = 0")) заголовок = true;
  // Хвост предыдущего куска остаётся приклеенным к следующему: иначе искомая
  // строка, разорванная границей чтения, не найдётся ни там, ни там.
  остаток = текст.slice(-64);
  хвост = текст.slice(-4096);
}

const беды = [];
if (размер < 10_000) беды.push(`файл подозрительно мал: ${размер} байт`);
if (таблиц < 5) беды.push(`в дампе всего ${таблиц} определений таблиц`);
if (!заголовок) беды.push("нет заголовка дампа");
if (!хвост.includes("SET FOREIGN_KEY_CHECKS = 1")) беды.push("нет завершающей строки — выгрузка оборвалась");

if (беды.length) {
  console.error("\nДамп не прошёл проверку:");
  беды.forEach(б => console.error(`  • ${б}`));
  console.error("Файл оставлен для разбора:", сырой);
  await appendFile(join(каталог, "backup.log"), `${new Date().toISOString()}  СБОЙ  ${беды.join("; ")}
`, "utf8").catch(() => {});
  process.exit(1);
}

// ── 3. Сжать ─────────────────────────────────────────────────────────────────
// В дампе сплошной текст, он ужимается в разы: место экономится существенно, а
// восстановление из .gz — та же одна команда.
await pipeline(createReadStream(сырой), createGzip({ level: 9 }), createWriteStream(сжатый));
await rm(сырой, { force: true });

const сжатыйРазмер = (await stat(сжатый)).size;

// ── 4. Убрать старые ─────────────────────────────────────────────────────────
// Без этого каталог растёт без предела, и однажды копия не запишется из-за
// нехватки места — то есть перестанет существовать ровно тогда, когда особенно
// нужна.
const все = (await readdir(каталог))
  .filter(f => f.startsWith("warehouse-pro-") && f.endsWith(".sql.gz"))
  .sort()
  .reverse();

const лишние = все.slice(хранить);
for (const ф of лишние) await rm(join(каталог, ф), { force: true });

// ── Итог ─────────────────────────────────────────────────────────────────────
const мб = (n) => (n / 1048576).toFixed(1);
console.log(`\nКопия готова: ${сжатый}`);
console.log(`  ${мб(размер)} МБ → ${мб(сжатыйРазмер)} МБ в сжатом виде`);
console.log(`  копий в каталоге: ${Math.min(все.length, хранить)}, удалено старых: ${лишние.length}`);
console.log(`\nВосстановление:`);
console.log(`  gzip -dc "${сжатый}" | mysql <строка-подключения>`);

// Строка в журнал рядом с копиями.
//
// По расписанию скрипт выполняется без окна, и весь вывод выше уходит в
// никуда. Журнал — единственное место, где потом видно, снималась копия или
// молча не снималась. Пишется он здесь, а не в обёртке: обёртка у разных
// способов запуска разная, а скрипт один.
await appendFile(
  join(каталог, "backup.log"),
  `${new Date().toISOString()}  ok  ${мб(сжатыйРазмер)} МБ  таблиц ${таблиц}  ${сжатый}\n`,
  "utf8",
).catch(() => {});
