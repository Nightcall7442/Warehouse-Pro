#!/usr/bin/env node
/**
 * Проверка типов для CI — с храповиком.
 *
 * ── Что было ────────────────────────────────────────────────────────────────
 *
 * В CI стояло `npx tsc --noEmit`. Корневой tsconfig.json — solution-файл:
 * "files": [] плюс три references. Для такой конфигурации `tsc --noEmit`
 * компилирует ПУСТОЙ набор и выходит с нулём: шаг «Type check» был зелёным,
 * ничего при этом не проверяя. Ссылки разворачивает только `tsc -b`, и его в
 * пайплайне не было.
 *
 * За это время накопилось 136 ошибок, причём 120 из них росли из одного корня
 * (нетипизированный cache.get, см. api/lib/cache.ts) и ломали вывод типов tRPC
 * на всём фронтенде. Среди прочего это скрывало настоящий баг: экран
 * супервайзера складывал планы всех агентов в одну группу, потому что читал
 * поле, которого сервер не отдавал.
 *
 * ── Почему храповик ─────────────────────────────────────────────────────────
 *
 * Проверка включалась, когда ошибок оставалось шесть: точечные несовпадения по
 * экранам, каждое требовало разбора. Ждать их, чтобы только потом включить
 * проверку, значило оставить дверь открытой — за это время натекло бы новых.
 *
 * Сейчас потолок ноль: все шесть разобраны. Почти все оказались одной и той же
 * ошибкой — рукописный тип в компоненте расходился с тем, что на самом деле
 * отдаёт сервер (Date против string, число против строки, «мешок неизвестного»
 * вместо разобранных полей).
 *
 * Храповик остаётся: появилась ошибка — сборка падает и называет её. Если
 * потолок когда-нибудь придётся поднять, это будет видно в истории отдельной
 * строкой, а не растворится в общем зелёном.
 */
import { execFileSync } from "node:child_process";

/** Сколько ошибок типов допускается. Только уменьшать. */
const BASELINE = 0;

// Компилятор запускается напрямую, а не через npx: npx на Windows — .cmd, и
// его пришлось бы звать через оболочку, а это лишний слой и предупреждение о
// неэкранированных аргументах.
const TSC = "node_modules/typescript/bin/tsc";

let output = "";
try {
  output = execFileSync(process.execPath, [TSC, "-b", "--pretty", "false"], {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  });
} catch (e) {
  // tsc выходит с ненулевым кодом при любых ошибках — это ожидаемо, разбираем вывод.
  output = `${e.stdout ?? ""}${e.stderr ?? ""}`;
}

const errors = output.split("\n").filter(l => /error TS\d+:/.test(l));
const count = errors.length;

console.log(`Ошибок типов: ${count}, потолок: ${BASELINE}`);

if (count > BASELINE) {
  console.error(`\nПоявились новые ошибки типов (${count} против ${BASELINE}).\n`);
  for (const line of errors) console.error(`  ${line}`);
  console.error(`\nПочините новые либо, если потолок поднимается осознанно, измените BASELINE в scripts/typecheck.mjs.`);
  process.exit(1);
}

if (count < BASELINE) {
  console.error(
    `\nОшибок стало меньше (${count} против ${BASELINE}) — это хорошо.\n` +
    `Опустите BASELINE в scripts/typecheck.mjs до ${count}, чтобы исправленное не вернулось незамеченным.`,
  );
  process.exit(1);
}

console.log("Потолок не превышен.");
