/** Пояс бизнеса: по нему экран показывает время и считает «сегодня». */
export const BUSINESS_TZ = "Asia/Tashkent";

/** Тот же пояс смещением в миллисекундах. */
export const BUSINESS_OFFSET_MS = 5 * 3_600_000;

/**
 * День «ГГГГ-ММ-ДД» по Ташкенту, в котором лежит момент времени, — на каком
 * бы поясе ни стояла машина, которая считает.
 */
export function businessDay(at: Date | string | number): string {
  return new Date(new Date(at).getTime() + BUSINESS_OFFSET_MS).toISOString().slice(0, 10);
}
