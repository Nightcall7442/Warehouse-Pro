/**
 * Дополнительные штрих-коды товара — общее для сервера и экрана.
 *
 * Предел один на обе стороны: форма не предлагает больше, чем примет сервер
 * (api/services/product-barcodes.ts), — иначе человек набрал бы двадцать
 * первый код и узнал об отказе только на «Сохранить».
 */

/** Сколько дополнительных кодов у одного товара: блок, пачка, пара поставщиков. */
export const MAX_EXTRA_BARCODES = 20;

/** Что отправить на сервер: список без пустых полей. Пустой список — «дополнительных нет». */
export function extraBarcodesPayload(value: readonly string[]): string[] {
  return value.map(v => v.trim()).filter(Boolean);
}
