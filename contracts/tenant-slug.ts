/*
  Адрес организации (slug) из её названия и слово для подтверждения удаления.

  Раньше slug строился заменой /[^\w\s-]/ — а \w в JavaScript без флага u
  это только латиница и цифры. Кириллица выбрасывалась целиком: «Борис
  Животное» получала ПУСТОЙ slug, «Прайм Дистрибюция» МЧЖ — «-1» (пустой
  уже был занят). Удалить такую организацию было нельзя: подтверждение
  требует набрать slug, а пустую строку сервер не принимает (01.10.2026).

  Теперь кириллица (русская и узбекская) переводится в латиницу по
  узбекскому обычаю (х → x, ҳ → h, ў → o), а если букв не осталось вовсе —
  «org». Уникальность (-1, -2…) по-прежнему добавляет вызывающий.
*/
const CYR: Record<string, string> = {
  а: "a", б: "b", в: "v", г: "g", д: "d", е: "e", ё: "yo", ж: "j", з: "z", и: "i", й: "y",
  к: "k", л: "l", м: "m", н: "n", о: "o", п: "p", р: "r", с: "s", т: "t", у: "u", ф: "f",
  х: "x", ц: "ts", ч: "ch", ш: "sh", щ: "sh", ъ: "", ы: "i", ь: "", э: "e", ю: "yu", я: "ya",
  ў: "o", қ: "q", ғ: "g", ҳ: "h",
};

export function slugify(name: string): string {
  const latin = [...name.toLowerCase().trim()].map(ch => CYR[ch] ?? ch).join("");
  const slug = latin
    .replace(/[^a-z0-9\s_-]/g, "")
    .replace(/[\s_]+/g, "-")
    .replace(/-{2,}/g, "-")
    .replace(/^-+|-+$/g, "");
  return slug || "org";
}

/**
 * Что набрать, чтобы подтвердить удаление организации: её slug, а если он
 * пустой (организации, заведённые до починки slugify) — её номер «#12».
 */
export function offboardConfirmWord(t: { id: number; slug: string | null }): string {
  const s = (t.slug ?? "").trim();
  return s ? s : `#${t.id}`;
}
