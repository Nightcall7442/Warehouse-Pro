import './index.css'
import { hadSession } from "@/lib/session-hint"

/*
  Входной файл: только выбор, что грузить.

  ── Что было ────────────────────────────────────────────────────────────────

  Гость, открывший warehouse-pro.uz, качал всё приложение: tRPC и
  react-query, Sentry с трассировкой, все страницы, которые App.tsx тянет
  сразу, подсказки установки PWA — 800 КБ входного файла ради лендинга. И
  ещё до первого кадра страница спрашивала сервер auth.me и
  warehouseMulti.list, хотя гостю отвечать на них нечем.

  ── Что теперь ──────────────────────────────────────────────────────────────

  Страницы сайта (/, /compare, /privacy, /uz, /uz/compare) сервер отдаёт
  готовым HTML, и в каждой стоит <meta name="wp-site">. Гостю на такой
  странице — лёгкий вход сайта (site/site-main): сама страница, форма заявки
  и Sentry без трассировки. Всем остальным — приложение (app-main), ровно как
  раньше:
    · вошедшему: сервер по куке сессии отдаёт на «/» оболочку без метки, а
      wp.hadSession в этом браузере говорит «ждите пользователя»;
    · установленной PWA без связи: service worker отдаёт закэшированную
      оболочку, в ней метки нет — приложение запускается офлайн, как прежде;
    · гостю на /login, /register, /pitch и прочих адресах приложения.

  Стили подключаются здесь: они общие, и готовый HTML сайта красится ими до
  первой строки скрипта.
*/
const sitePage = document.querySelector('meta[name="wp-site"]')?.getAttribute("content");

if (sitePage && !hadSession()) void import("./site/site-main")
else void import("./app-main")
