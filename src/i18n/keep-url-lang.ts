import { useCallback } from "react";
import { hasChosenLang, useLang } from "./index";

/*
  Отдельным модулем, а не в ./index: экраны входа и регистрации проверяются
  с подменённым @/i18n (только useLang и useTranslate), и новый экспорт там
  ронял бы их проверки, не относящиеся к языку.
*/

/**
 * Язык адреса — в сохранённый выбор, когда человек довёл дело до конца на
 * этом языке: зарегистрировался или вошёл с /register?lang=uz.
 *
 * Сам заход по ссылке выбором не считается (UrlLang), но дальше адрес языка
 * уже не несёт: письмо подтверждения, вход, первые шаги в приложении берут
 * сохранённый выбор, а без него — русский. Узбекоязычный директор,
 * прошедший регистрацию по-узбекски, получал приложение по-русски. Выбор,
 * сделанный раньше в этом браузере, сильнее: его не трогаем.
 */
export function useKeepUrlLang(): () => void {
  const { lang, setLang, fromUrl } = useLang();
  return useCallback(() => {
    if (fromUrl && !hasChosenLang()) setLang(lang);
  }, [fromUrl, lang, setLang]);
}
