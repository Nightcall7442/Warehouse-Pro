/* ═══════════════════════════════════════════════════════════════════════════
   Состояния записей так, как они называются на бумаге.

   ── Зачем это здесь, а не в реестре отчётов ─────────────────────────────────

   Словари заводились для реестра отчётов, когда выяснилось, что в файлы
   уходит значение колонки как есть: «active», «pending», «unloading». Там их
   и починили — а выгрузки из lib/excel.ts, которые зовут из девятнадцати
   мест, остались с кодами: «Status: active», «Роль: ceo».

   Это ровно тот же случай, что с разбором движений товара: чинили по очереди
   пять мест, потому что общего словаря не было. Здесь он есть, и второй копии
   не будет.

   ── Правило про неизвестное значение ────────────────────────────────────────

   Незнакомое значение показывается как есть, а не прячется. Промолчать о нём
   хуже: человек хотя бы увидит, что появилось новое состояние, и спросит.
   Пусто — это прочерк, а не пустая клетка: в таблице их не отличить от
   потерянных данных.
   ═══════════════════════════════════════════════════════════════════════════ */

