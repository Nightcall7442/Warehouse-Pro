/**
 * Как выглядит магазин, у которого нет фотографии.
 *
 * ── Что было ────────────────────────────────────────────────────────────────
 *
 * Один и тот же серый значок лавки у всех. В списке из двухсот точек это стена
 * одинаковых картинок: глазом зацепиться не за что, строки различаются только
 * подписью, и найти нужную можно лишь прочитав их подряд.
 *
 * ── Как теперь ──────────────────────────────────────────────────────────────
 *
 * Цвет выводится из номера магазина, а не назначается вручную: он не меняется
 * при перезагрузке, при смене порядка сортировки и при переименовании точки.
 * Человек запоминает «мой Анжир — зелёный» и находит его взглядом.
 *
 * Поверх — инициалы. Значок лавки одинаков у всех по определению, а инициалы
 * различают точки между собой; сама лавка остаётся водяным знаком, чтобы
 * плашка читалась как «фото магазина», а не как аватар человека.
 *
 * ── Почему цвета числом ─────────────────────────────────────────────────────
 *
 * Это палитра ДАННЫХ, как цвета рядов у графика: нужно восемь различимых
 * оттенков, а переменных темы столько нет. Обе пары подобраны так, чтобы белые
 * буквы читались и на светлой, и на тёмной теме — плашка везде одна и та же,
 * это и делает её приметой.
 */

/** Восемь пар «от / до» для заливки. Порядок неважен, важна устойчивость. */
const TILES: ReadonlyArray<readonly [string, string]> = [
  ["#5b6d8a", "#3f4d63"], // сине-серый
  ["#3a9a8a", "#2b7468"], // бирюзовый
  ["#c06080", "#94465f"], // розовый
  ["#c49530", "#946f22"], // янтарный
  ["#7a6db5", "#5b5189"], // фиолетовый
  ["#3a9ab5", "#2b7488"], // голубой
  ["#5f9a4a", "#477538"], // зелёный
  ["#b5643a", "#8a4a2b"], // терракотовый
];

/**
 * Устойчивый разброс по номеру.
 *
 * Умножение с примешиванием, а не просто `id % 8`: подряд идущие номера иначе
 * дают подряд идущие цвета, и список выходит радугой по порядку заведения — то
 * есть узором, а не приметой.
 */
export function shopTile(id: number): readonly [string, string] {
  const mixed = Math.abs(Math.imul(id, 2654435761)) >>> 0;
  return TILES[mixed % TILES.length];
}

/**
 * Инициалы названия — одна или две буквы.
 *
 * Берутся только буквы: у точек попадаются названия вроде «ЧП "Барака"», и
 * кавычка в плашке выглядела бы опечаткой. Если букв нет вовсе — пусто, и
 * рисуется значок лавки.
 */
export function shopInitials(name: string): string {
  const words = name
    .split(/[\s,./\\-]+/)
    .map(w => w.replace(/[^\p{L}\p{N}]/gu, ""))
    .filter(Boolean);

  if (words.length === 0) return "";
  if (words.length === 1) return words[0].slice(0, 2).toUpperCase();
  return (words[0][0] + words[1][0]).toUpperCase();
}
