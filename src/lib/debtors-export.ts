/* ═══════════════════════════════════════════════════════════════════════════
   Должники и их долги — одним файлом.

   ── Зачем ───────────────────────────────────────────────────────────────────

   «Кому мы отгрузили и не получили денег» — вопрос, который задают чаще
   остальных, и до сих пор ответ на него можно было получить только в разделе
   отчётов, отдельной карточкой выгрузки. На самой странице магазинов, где
   человек этот долг и видит, забрать его файлом было нельзя.

   ── Почему возраст, а не только сумма ───────────────────────────────────────

   Двенадцать миллионов недельного долга и двенадцать миллионов полугодового —
   это две разные организации: в первой деньги в обороте, во второй их уже
   почти нет. Поэтому в файле рядом с суммой стоит возраст самого старого
   неоплаченного заказа и корзина, в которую он попадает.

   ── Почему «не привязано к заказу» отдельной колонкой ───────────────────────

   Долг магазина складывается не только из заказов: бывают ручные начисления и
   возвраты, у которых своей даты обязательства нет. Состарить их нельзя, и
   замолчать тоже: отчёт, части которого не дают итог, хуже отсутствующего.
   ═══════════════════════════════════════════════════════════════════════════ */

/** Строка, какой её отдаёт shop.receivablesAging. */
export interface DebtorRow {
  shopId: number;
  shopName: string;
  debt: number;
  buckets: Record<string, number>;
  unattributed: number;
  oldestDays: number | null;
}

/** Возрастные корзины в том порядке, в каком их читают. */
export const DEBT_BUCKETS = [
  { key: "d0_7",    ru: "до 7 дней",   uz: "7 kungacha" },
  { key: "d8_30",   ru: "8–30 дней",   uz: "8–30 kun" },
  { key: "d31_60",  ru: "31–60 дней",  uz: "31–60 kun" },
  { key: "d60plus", ru: "больше 60",   uz: "60 kundan ko'p" },
] as const;

/** Корзина, в которую попадает самый старый долг магазина. */
export function oldestBucket(days: number | null, lang = "ru"): string {
  if (days === null) return "—";
  const b = days <= 7 ? DEBT_BUCKETS[0]
    : days <= 30 ? DEBT_BUCKETS[1]
    : days <= 60 ? DEBT_BUCKETS[2]
    : DEBT_BUCKETS[3];
  return lang === "uz" ? b.uz : b.ru;
}

/**
 * Строки для файла: только те, кто действительно должен.
 *
 * Магазин с нулевым долгом в выборку сервера попадает (по нему может быть
 * открытый заказ), но должником не является — в файле «Должники» ему не место.
 *
 * Числа уходят ЧИСЛАМИ: в выгрузке их складывают и сортируют, а строка «12
 * 500,00» ни того, ни другого не позволяет.
 */
export function formatDebtorsForExport(shops: DebtorRow[], lang = "ru") {
  const L = (ru: string, uz: string) => (lang === "uz" ? uz : ru);
  return shops
    .filter(s => s.debt > 0)
    .slice()
    .sort((a, b) => b.debt - a.debt)
    .map(s => ({
      [L("Магазин", "Do'kon")]: s.shopName,
      [L("Долг", "Qarz")]: s.debt,
      [L("Дней с самого старого", "Eng eskisidan kun")]: s.oldestDays ?? "—",
      [L("Возраст", "Yosh")]: oldestBucket(s.oldestDays, lang),
      [L("до 7 дней", "7 kungacha")]: s.buckets.d0_7 ?? 0,
      [L("8–30 дней", "8–30 kun")]: s.buckets.d8_30 ?? 0,
      [L("31–60 дней", "31–60 kun")]: s.buckets.d31_60 ?? 0,
      [L("больше 60", "60 kundan ko'p")]: s.buckets.d60plus ?? 0,
      [L("Не привязано к заказу", "Buyurtmaga bog'lanmagan")]: s.unattributed,
    }));
}
