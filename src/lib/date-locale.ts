import { ru, uz } from "date-fns/locale";
import type { Lang } from "@/i18n";

/*
  Язык дат — тот же, что у экрана.

  До 20.09.2026 каждый экран решал сам: одни писали `{ locale: ru }` и в
  узбекском интерфейсе показывали «воскресенье, 20 сентября»; другие —
  `lang === "uz" ? undefined : ru` и показывали «20 September» — английский,
  потому что без локали date-fns говорит по-английски. Теперь одна дверь:
  экран передаёт язык, здесь выбирается словарь. Узбекский — латиница, как
  и весь интерфейс (Sozlamalar, Buyurtmalar).

  Бумага (печать, Excel) сюда не ходит — она остаётся русской.
*/
export function dateLocale(lang: Lang) {
  return lang === "uz" ? uz : ru;
}
