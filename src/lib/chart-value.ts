/**
 * Число в подсказке графика и подпись оси.
 *
 * ── Почему это отдельный файл ───────────────────────────────────────────────
 *
 * Потому что подсказка к графику написана в проекте пять раз, и в каждой копии
 * форматирование своё. Утром одну из них починили — а на «Остатках по
 * категориям» в подсказке по-прежнему стояло
 *
 *     Стоимость: 243775609.0000
 *
 * потому что у той страницы копия своя. MySQL отдаёт DECIMAL строкой, и
 * проверка `typeof v === "number"` такую строку не ловит: она уходит на экран
 * как есть — с четырьмя знаками после запятой и без разделителей разрядов.
 * Прочитать «243775609.0000» как двести сорок три миллиона нельзя.
 */

/** Число для подсказки: разделители разрядов, не больше двух знаков дроби. */
export function formatChartValue(v: number | string | undefined | null): string {
  if (v === undefined || v === null) return "—";
  const n = typeof v === "number" ? v : Number(v);
  // Не число — показываем как пришло: подпись вида «нет данных» портить нельзя.
  if (!Number.isFinite(n)) return String(v);
  // Два знака — потолок, а не обязанность: у целых чисел хвост не рисуется.
  return n.toLocaleString("ru", { maximumFractionDigits: 2 });
}

/**
 * Подпись категории, укладывающаяся в отведённую ширину.
 *
 * Сокращение идёт по СЕРЕДИНЕ, а не с конца. Названия категорий в этом
 * хозяйстве различаются как раз хвостом:
 *
 *     Влажные салфетки (для женщин)
 *     Влажные салфетки (для мужчин)
 *
 * Обрежь их с конца — обе превратятся в «Влажные салфетки (дл…», и график
 * станет двумя одинаковыми строками с разной длиной столбца. Середина же
 * теряется без потери смысла: «Влажные салф…(для мужчин)».
 */
export function truncateMiddle(text: string, maxChars: number): string {
  if (text.length <= maxChars) return text;
  // Единица — на сам многоточный знак.
  const keep = maxChars - 1;
  const head = Math.ceil(keep / 2);
  const tail = Math.floor(keep / 2);
  return `${text.slice(0, head)}…${text.slice(text.length - tail)}`;
}
