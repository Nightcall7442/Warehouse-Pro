/**
 * Скидка заказа: в базе — деньги, в ручке обновления — проценты.
 *
 * Договор такой (api/services/order.ts:1433): клиент присылает процент,
 * сервер сам умножает его на сумму заказа и кладёт в базу деньги. Значит
 * форма редактирования обязана делать обратное преобразование, показывая
 * человеку процент.
 *
 * Пересчёт жил в двух местах и только в одном был верным. В OrderSlideOver
 * его написали правильно, в OrderDetail — забыли, и в поле «Скидка (%)»
 * подставлялась сумма в сумах. Дальше одно из двух:
 *
 *   • скидка 5000 сум → поле «5000» → проверка «от 0 до 100» не пускает, и
 *     заказ становится нередактируемым целиком: ни примечание, ни способ
 *     оплаты не поменять;
 *   • скидка 50 сум → поле «50» → сохраняется как 50 ПРОЦЕНТОВ, и сервер
 *     режет заказ вдвое. Молча, с зелёным «Заказ обновлён».
 *
 * Поэтому пересчёт здесь один на всех и проверен тестом.
 */

/** Скидка в процентах от суммы заказа — то, что показывают в форме. */
export function discountMoneyToPct(order: {
  discount?: string | number | null;
  subtotal?: string | number | null;
}): number {
  const subtotal = Number(order.subtotal ?? 0);
  // Заказ на ноль (или сумма не пришла) — процента не существует. Делить
  // нельзя, а показать что-то надо: ноль честнее NaN в поле ввода.
  if (!Number.isFinite(subtotal) || subtotal <= 0) return 0;

  const money = Number(order.discount ?? 0);
  if (!Number.isFinite(money) || money <= 0) return 0;

  // Два знака: столько же принимает поле, и столько же переживает обратный
  // пересчёт на сервере без заметного расхождения в сумах.
  return Math.round((money / subtotal) * 10000) / 100;
}
