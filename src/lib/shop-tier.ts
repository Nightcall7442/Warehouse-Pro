/**
 * Размер картинки метки и точка привязки.
 *
 * Первый размер был 30×40 — на живой карте булавка вышла с ноготь: рядом
 * стоят подписи улиц и значки самого Яндекса примерно того же роста, и метка
 * среди них не читалась. Крупнее ровно настолько, чтобы цвет узнавался без
 * наведения и не приходилось приближать карту.
 *
 * Разметка та же, меняются только width и height при неизменном viewBox —
 * вектор тянется без потерь.
 *
 * Привязка идёт к ТЕНИ, а не к острию: булавка нарисована приподнятой над
 * землёй, и на адресе магазина стоит именно пятно тени — cy=37 из 40 по
 * высоте картинки, то есть 59 из 64.
 */
export const PIN_SIZE: [number, number] = [48, 64];
export const PIN_ANCHOR: [number, number] = [-24, -59];

/**
 * Выше этого числа меток анимация выключается.
 *
 * Каждая метка — отдельная картинка, и SMIL в ней браузер считает сам. Два
 * десятка плавающих булавок выглядят живо, три сотни съедают кадры и греют
 * ноутбук, ради эффекта, которого на такой плотности всё равно не видно.
 */
export const PIN_ANIMATION_LIMIT = 60;

/**
 * Булавка магазина.
 *
 * Раньше здесь был плоский квадрат 20×20. На карте Яндекса он терялся среди
 * её собственных значков — метро, аптек, банкоматов — и читался как артефакт
 * отрисовки, а не как объект приложения. Отсюда и «выглядит как треш».
 *
 * Что делает форму меткой, а не пятном:
 *   • силуэт булавки с остриём — глаз узнаёт его как «точка на местности»,
 *     и привязка идёт к острию, то есть метка стоит ровно на своём адресе,
 *     а не парит центром над ним;
 *   • тень на земле — она отделяет метку от подложки и даёт ту самую
 *     «плавающесть»;
 *   • белая обводка — карта под меткой бывает любого цвета, без обводки
 *     красная булавка сливается с красной линией метро;
 *   • значок лавки внутри — цвет говорит «как платит», а форма должна
 *     говорить «это магазин».
 */
export function shopPinSvg(color: string, animated: boolean): string {
  const float = animated
    ? `<animateTransform attributeName="transform" type="translate"
         values="0 0; 0 -2.2; 0 0" keyTimes="0;0.5;1" dur="3s"
         calcMode="spline" keySplines="0.4 0 0.6 1; 0.4 0 0.6 1"
         repeatCount="indefinite"/>`
    : "";
  // Тень дышит вместе с булавкой: когда та поднимается, пятно чуть меньше и
  // светлее. Без этого «полёт» читается как дрожание.
  const shadowPulse = animated
    ? `<animate attributeName="rx" values="5;3.8;5" keyTimes="0;0.5;1" dur="3s"
         calcMode="spline" keySplines="0.4 0 0.6 1; 0.4 0 0.6 1" repeatCount="indefinite"/>
       <animate attributeName="opacity" values="0.22;0.13;0.22" keyTimes="0;0.5;1" dur="3s"
         calcMode="spline" keySplines="0.4 0 0.6 1; 0.4 0 0.6 1" repeatCount="indefinite"/>`
    : "";

  return `<svg xmlns="http://www.w3.org/2000/svg" width="48" height="64" viewBox="0 0 30 40">
  <ellipse cx="15" cy="37" rx="5" ry="1.7" fill="#000" opacity="0.22">${shadowPulse}</ellipse>
  <g>${float}
    <path d="M15 1.6c-5.3 0-9.6 4.2-9.6 9.4 0 6.8 8.4 14.9 8.7 15.3.5.5 1.3.5 1.8 0 .3-.4 8.7-8.5 8.7-15.3 0-5.2-4.3-9.4-9.6-9.4z"
          fill="${color}" stroke="#ffffff" stroke-width="2"/>
    <path d="M9.6 7.4h10.8l.9 2.5H8.7z" fill="#ffffff"/>
    <path d="M10.3 10.6h9.4v5.1h-9.4z" fill="#ffffff"/>
    <rect x="13.3" y="12.1" width="3.4" height="3.6" rx="0.4" fill="${color}"/>
  </g>
</svg>`;
}
