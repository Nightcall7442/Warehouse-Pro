/**
 * Метка магазина на карте.
 *
 * Значения цветов — обычные шестнадцатеричные, а не токены темы, и это не
 * небрежность: метки Яндекс.Карт рисуются SVG внутри data-URI, а туда
 * переменная CSS не доходит — `var(--color-success-text)` внутри
 * `data:image/svg+xml` браузер подставить не может, и метка выходит чёрной.
 * На метке агента в SupervisorTracking ошибка ровно такая и была.
 */

