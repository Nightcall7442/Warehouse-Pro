/**
 * Ввод дробных чисел: цены, суммы, вес, количество.
 *
 * Поля с type="number" тихо теряют введённое. В настоящем браузере с русской
 * локалью «12,5» даёт value === "" — и checkValidity() при этом возвращает
 * true, потому что пустое непомеченное поле считается заполненным верно. Ни
 * браузер, ни форма ничего не сообщают. Пустая строка уходит на сервер, где
 * превращается в значение по умолчанию, то есть в ноль.
 *
 * Так цена товара становилась нулевой оттого, что человек нажал запятую —
 * клавишу, которая на цифровой части клавиатуры стоит там, где в русской
 * записи и положено быть разделителю. То же самое с вставкой из буфера:
 * «1 250» тоже даёт пустую строку.
 *
 * Поэтому такие поля переведены на обычный текстовый ввод с цифровой
 * клавиатурой, а введённое приводится к виду, понятному серверу.
 */

/** Пробелы, которыми разделяют тысячи, включая неразрывный и узкий. */
const SPACES = /[\s\u00A0\u202F\u2009']/g;

/**
 * Привести введённое к записи с точкой.
 *
 * Вызывается на каждое нажатие, поэтому обязана пропускать незаконченный
 * ввод: «12.» посреди набора «12.5» — нормальное состояние, обрезать его
 * нельзя, иначе точку невозможно поставить.
 */
export function normalizeDecimalInput(raw: string): string {
  let s = raw.replace(SPACES, "").replace(/,/g, ".");

  const negative = s.startsWith("-");
  s = s.replace(/[^0-9.]/g, "");

  // Набранное после второй точки отбрасывается вместе с ней. Склеить
  // «12.5.7» в «12.57» значило бы выдумать сумму, которую не вводили, — а это
  // ровно та беда, ради которой поле и переписано.
  const first = s.indexOf(".");
  if (first !== -1) {
    const second = s.indexOf(".", first + 1);
    if (second !== -1) s = s.slice(0, second);
  }

  return negative ? "-" + s : s;
}

/**
 * Число из введённого — или null, если числа там нет.
 *
 * Отдельно от Number() потому, что Number("") === 0: пустое поле нельзя
 * молча считать нулём, именно на этом цены и обнулялись.
 */
export function parseDecimalInput(raw: string | null | undefined): number | null {
  if (raw === null || raw === undefined) return null;
  const s = normalizeDecimalInput(String(raw));
  if (s === "" || s === "-" || s === "." || s === "-.") return null;
  const n = Number(s);
  return Number.isFinite(n) ? n : null;
}

/** Пригодно ли введённое для отправки на сервер как десятичное число. */
export function isDecimalInput(raw: string | null | undefined): boolean {
  return parseDecimalInput(raw) !== null;
}
