/**
 * Значение переменной темы обычным цветом.
 *
 * Нужно там, где переменную некуда передать: SVG внутри `data:`-адреса — это
 * отдельный документ, переменных страницы он не видит, и `fill="var(--…)"`
 * там не разбирается вовсе. Метка от этого не «берёт цвет по умолчанию», а
 * становится ЧЁРНОЙ: непонятое значение presentation-атрибута отбрасывается, и
 * остаётся начальное — black. Так и вышло на двух картах: у курьера все метки
 * доставок оказались одинаково чёрными вместо оранжевой/зелёной/синей, а у
 * супервайзера агент в сети выглядел ровно как не в сети.
 *
 * Читается в момент отрисовки, а не один раз при загрузке модуля: тема
 * переключается на лету, и запомненное значение осталось бы от прежней.
 *
 * В обычном SVG на странице (графики, кольца) var() работает — там подмена не
 * нужна и делать её незачем.
 */
export function cssVar(name: string, fallback: string): string {
  if (typeof document === "undefined") return fallback;
  const value = getComputedStyle(document.documentElement).getPropertyValue(name).trim();
  return value || fallback;
}
