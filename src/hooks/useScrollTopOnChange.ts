import { useEffect, useRef } from "react";

/**
 * Показать список сверху, когда сменилась страница.
 *
 * ── Что было ────────────────────────────────────────────────────────────────
 *
 * Жалоба владельца: «при переходе на следующую страницу список не
 * возвращается к началу, а открывается с середины или конца — везде».
 *
 * Кнопка «Далее» стоит под списком. Человек нажимает её, стоя внизу
 * страницы; строки подменяются, а положение прокрутки остаётся — и он
 * смотрит на конец второй страницы, не видя её начала. Браузер сам ничего не
 * делает: адрес не меняется, страница та же.
 *
 * ── Что здесь ───────────────────────────────────────────────────────────────
 *
 * При смене ключа (номер страницы; можно и фильтр) окно прокручивается к
 * началу списка, если передан его элемент, иначе — к началу страницы. Над
 * списком остаётся зазор в 72 px: на узком экране вверху висит закреплённая
 * шапка в 56 px, и без зазора она накрыла бы заголовок таблицы. Без
 * плавности: мгновенный переход читается как «открылась новая страница»,
 * плавный — как «экран уехал сам».
 */
const HEADROOM = 72;

export function useScrollTopOnChange(key: unknown, listRef?: React.RefObject<HTMLElement | null>): void {
  const first = useRef(true);
  useEffect(() => {
    // Первый показ и так начинается сверху.
    if (first.current) { first.current = false; return; }
    const rect = listRef?.current?.getBoundingClientRect();
    // Начало списка уже на экране — не трогаем: человек его видит.
    if (rect && rect.top >= 0) return;
    const top = rect ? rect.top + window.scrollY - HEADROOM : 0;
    window.scrollTo({ top: Math.max(0, top), behavior: "auto" });
  }, [key, listRef]);
}
