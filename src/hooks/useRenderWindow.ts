import { useState } from "react";

/** Сколько карточек рисуется сразу и сколько добавляет «Показать ещё». */
export const RENDER_WINDOW = 100;

/**
 * Окно отрисовки длинного списка: первые `page` строк сразу, дальше по кнопке.
 *
 * ── Что было ────────────────────────────────────────────────────────────────
 *
 * «Магазины» агента рисовали каждую точку организации карточкой — у крупного
 * клиента это тысячи карточек и десятки тысяч узлов DOM. Дешёвый Android
 * открывал раздел секундами, а поиск перерисовывал всё на каждую букву.
 *
 * ── Что теперь ──────────────────────────────────────────────────────────────
 *
 * Режется только отрисовка: фильтр и поиск по-прежнему идут по ВСЕМУ списку
 * у вызывающего, сюда приходит уже отобранное. Окно сбрасывается на новый
 * ключ (поиск, режим, территория) прямо при отрисовке, без эффекта — тот же
 * приём, что у «Склада» (pages/Warehouse.tsx): новый поиск начинает с начала,
 * а лишнего кадра со старым окном нет.
 */
export function useRenderWindow<T>(items: readonly T[], key: string, page: number = RENDER_WINDOW) {
  const [win, setWin] = useState({ key, rows: page });
  if (win.key !== key) setWin({ key, rows: page });
  const rows = win.key === key ? win.rows : page;
  return {
    shown: items.slice(0, rows),
    /** Сколько ещё не нарисовано. */
    hidden: Math.max(0, items.length - rows),
    /** Сколько добавит следующее нажатие. */
    step: page,
    more: () => setWin(w => ({ key, rows: (w.key === key ? w.rows : page) + page })),
  };
}
