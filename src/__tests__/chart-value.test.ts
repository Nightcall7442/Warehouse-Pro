/**
 * Числа и подписи на графиках.
 *
 * Два дефекта с одного экрана — «Остатки по категориям»:
 *
 *   1. В подсказке стояло «Стоимость: 243775609.0000». MySQL отдаёт DECIMAL
 *      строкой, а проверка `typeof v === "number"` такую строку не ловит и
 *      выводит как есть: четыре знака после запятой и ни одного разделителя
 *      разрядов. Прочитать это как двести сорок три миллиона нельзя.
 *
 *      Утром такую же подсказку уже чинили — в другом файле. Копий у неё в
 *      проекте пять, и починка одной остальных не касалась.
 *
 *   2. Подписи категорий налезали друг на друга: при ширине 75 и шрифте 11
 *      длинное название переносилось на три строки, а на строку графика
 *      приходится тридцать пять точек.
 */
import { describe, it, expect } from "vitest";
import { formatChartValue, truncateMiddle } from "../lib/chart-value";

/**
 * Разряды toLocaleString разделяет НЕРАЗРЫВНЫМ пробелом (U+00A0). На экране он
 * неотличим от обычного, в сравнении строк — отличим, и первая версия этих
 * проверок падала с «expected 243 775 609 to be 243 775 609». Приводим к
 * обычному пробелу, чтобы сравнивать смысл, а не невидимый знак.
 */
const plain = (v: string) => v.replace(/\u00A0/g, " ");

describe("число в подсказке", () => {
  it("сумма из базы читается человеком", () => {
    // Ровно то значение, что стояло на экране.
    expect(plain(formatChartValue("243775609.0000"))).toBe("243 775 609");
  });

  it("копейки остаются, если они есть", () => {
    expect(plain(formatChartValue("1234.50"))).toBe("1 234,5");
  });

  it("число приходит числом — работает так же", () => {
    expect(plain(formatChartValue(243775609))).toBe("243 775 609");
  });

  it("пусто — прочерк, а не ноль", () => {
    // Ноль означал бы «остатка нет», а это неправда: данных просто не пришло.
    expect(formatChartValue(undefined)).toBe("—");
    expect(formatChartValue(null)).toBe("—");
  });

  it("не число показывается как есть", () => {
    // Подпись вида «нет данных» портить нельзя.
    expect(formatChartValue("нет данных")).toBe("нет данных");
  });
});

describe("подпись категории", () => {
  it("короткая остаётся целой", () => {
    expect(truncateMiddle("Жидкое мыло", 26)).toBe("Жидкое мыло");
  });

  it("длинная сокращается по середине", () => {
    const out = truncateMiddle("Влажные салфетки (антибактериальные)", 26);
    expect(out.length).toBe(26);
    expect(out).toContain("…");
  });

  it("категории, различающиеся хвостом, остаются различимыми", () => {
    // Главное, ради чего сокращение идёт по середине. Обрезка с конца
    // превратила бы обе в «Влажные салфетки (дл…» — две одинаковые подписи
    // с разной длиной столбца.
    const women = truncateMiddle("Влажные салфетки (для женщин)", 26);
    const men = truncateMiddle("Влажные салфетки (для мужчин)", 26);

    expect(women).not.toBe(men);
    expect(women).toContain("женщин)");
    expect(men).toContain("мужчин)");
  });

  it("сокращённое всегда короче отведённого", () => {
    for (const name of [
      "Средства для мытья посуды",
      "Жидкие средства для стирки",
      "Бумажные салфетки",
      "Влажные салфетки (детские)",
      "Очень длинное название категории, каких в справочнике не бывает",
    ]) {
      expect(truncateMiddle(name, 26).length).toBeLessThanOrEqual(26);
    }
  });
});
