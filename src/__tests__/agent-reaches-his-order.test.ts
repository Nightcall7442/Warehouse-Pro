import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * До заказа агент доходит СВОИМ путём, и всё нужное должно быть на нём.
 *
 * ── Что нашлось ─────────────────────────────────────────────────────────────
 *
 * В вебе два разных экрана заказа:
 *
 *   • OrderSlideOver — панель, которая выезжает из списка ОПЕРАТОРА;
 *   • OrderDetail    — карточка по адресу /orders/:id.
 *
 * Агент видит свой список (AgentOrders) и открывает из него именно карточку.
 * А переписка по заказу и правка состава стояли только в панели оператора —
 * то есть обе ручки агенту открыты, экран написан, а дойти до него нельзя.
 *
 * Та же болезнь, что и с мёртвыми ручками, только на шаг ближе к человеку:
 * ручку зовут, но с чужого экрана.
 *
 * ── Почему проверка по исходнику ────────────────────────────────────────────
 *
 * Вопрос здесь не «как выглядит», а «смонтировано ли на том экране». Поднимать
 * ради этого настоящий React с роутером и ролями дороже, чем польза: сломается
 * это не отрисовкой, а тем, что блок положат не в тот файл.
 */
const read = (p: string) => readFileSync(join(process.cwd(), p), "utf8").replace(/\r\n/g, "\n");

/** Убрать комментарии: упоминание — не монтирование. */
const strip = (code: string) =>
  code.replace(/\/\*[\s\S]*?\*\//g, " ").replace(/(^|[^:])\/\/.*$/gm, "$1");

const DETAIL = strip(read("src/pages/OrderDetail.tsx"));
const AGENT_LIST = strip(read("src/pages/AgentOrders.tsx"));
const ORDERS = strip(read("src/pages/Orders.tsx"));
const APP = strip(read("src/App.tsx"));

describe("агент попадает именно в карточку заказа", () => {
  it("его список ведёт на /orders/:id", () => {
    /*
      Если он начнёт вести куда-то ещё, проверки ниже перестанут стеречь то
      место, где агент на самом деле работает, — и замолчат.
    */
    expect(AGENT_LIST, "список агента больше не ведёт в карточку заказа")
      .toMatch(/navigate\(`\/orders\/\$\{[^}]+\}`\)/);
  });

  it("агенту показывают его список, а не операторский", () => {
    expect(ORDERS).toContain('user?.role === "agent"');
    expect(ORDERS).toContain("<AgentOrders />");
  });

  it("карточка заказа открыта агенту", () => {
    const at = APP.indexOf('path="/orders/:id"');
    expect(at, "маршрут карточки заказа не найден").toBeGreaterThan(0);
    expect(APP.slice(at, APP.indexOf("/>", at)), "карточка заказа закрыта агенту").toContain('"agent"');
  });
});

describe("на этом экране есть всё, что агенту открыто", () => {
  it("переписка по заказу", () => {
    /*
      Обе ручки (order.listComments, order.addComment) — fieldSalesQuery, то
      есть агенту открыты, и сервер сам не пускает в чужой заказ. А блок стоял
      только в панели оператора: агент не видел переписки о СВОЁМ заказе и не
      мог ответить.
    */
    expect(DETAIL, "переписки нет в карточке заказа").toContain("<OrderComments orderId={order.id} />");
  });

  it("правка состава", () => {
    // Просьба владельца: агент добавляет товары, убирает их и меняет
    // количество. Правка жила только в панели оператора.
    /*
      Проверяется УСЛОВИЕ, под которым он стоит, а не наличие имени в файле.
      «toContain("<OrderItemsEditor")» находило и `{null && <OrderItemsEditor}`
      — страж молчал на сломе, потому что подстрока никуда не делась.
    */
    // Имя целиком, а не по началу: «<OrderItemsEditorGone» тоже содержит
    // «<OrderItemsEditor», и переименование прошло бы мимо стража.
    const tag = DETAIL.match(/<OrderItemsEditor(?![A-Za-z0-9_])/);
    expect(tag, "правки состава нет в карточке заказа").not.toBeNull();
    const at = tag!.index!;
    const before = DETAIL.slice(DETAIL.lastIndexOf("{", at), at).trim();
    expect(before, "правка состава выключена или открыта не тому").toBe("{canEditItems && (");
  });

  it("правка состава не показывается там, где сервер откажет", () => {
    /*
      Границы те же, что на сервере: свой заказ и пока он не уехал. Повторены
      на экране не вместо проверки, а чтобы не обещать того, чего не будет:
      кнопка, ведущая в отказ, хуже отсутствующей кнопки.
    */
    expect(DETAIL).toContain("const isAuthor =");
    expect(DETAIL).toContain("FIELD_EDITABLE_ORDER_STATUSES");
    expect(DETAIL, "правка состава открыта на удалённом заказе").toContain("!order?.deletedAt");
  });

  it("удалённый заказ не комментируют", () => {
    // Удаление — штатный способ исправить ошибочно проведённый заказ.
    // Переписка о том, чего больше нет, только сбивает.
    expect(DETAIL).toContain("{!order.deletedAt && <OrderComments");
  });
});
