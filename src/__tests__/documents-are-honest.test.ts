/**
 * Печатные документы говорят правду и не занимают место впустую.
 *
 * ── Что нашлось при разборе ─────────────────────────────────────────────────
 *
 * Владелец сказал: «накладные вообще тупые везде, некрасивые, не компактные,
 * абсолютно непрофессионально». Причины оказались конкретными.
 *
 * 1. В ТОРГ-12 сумма подписывалась «руб.» — жёстко, при том что двумя
 *    строками выше валюта берётся из настроек арендатора. Организация в
 *    Узбекистане печатала товарную накладную с рублями.
 *
 * 2. Там же стояло «Итого мест: 1» — тоже жёстко. Число мест это количество
 *    тарных единиц, и система его не знает: такого поля нет в данных вовсе.
 *    По товарной накладной принимают груз, и выдуманная единица там опаснее
 *    пустого места.
 *
 * 3. Реквизиты печатались всегда, все шесть строк. У арендатора, заполнившего
 *    одно название, накладная выходила с пятью строками, после двоеточия в
 *    которых не было ничего, — вот это и есть «не компактно».
 *
 * 4. Номер и дата документа подставлялись без экранирования, тогда как всё
 *    остальное в файле экранируется (118 мест). Номер прихода заводят руками.
 *
 * 5. В приходной накладной графа «Состояние» заполнялась словом «Хорошее» для
 *    каждой строки: поля condition в данных документа нет, приведение типа
 *    всегда давало undefined. Эту графу подписывает кладовщик.
 *
 * 6. В ТТН стояла ставка НДС 0% в каждой строке и две одинаковые графы —
 *    «Цена без НДС» и «Цена с НДС» с одним и тем же числом. НДС система не
 *    считает: onec-vat.ts к заказам не подключён.
 *
 * 7. В ТОРГ-12 строка съехала относительно шапки: артикул попадал в графу
 *    кода ОКЕИ, количество печаталось дважды — второй раз как «мест, штук».
 */
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

const DOCS = readFileSync(join(__dirname, "..", "lib", "documents.ts"), "utf8");

describe("документы не выдумывают того, чего не знают", () => {
  it("валюта берётся у арендатора, а не вписана словом", () => {
    /*
      Ищем денежные подписи прямо в разметке. «сум» и «so'm» тоже нельзя:
      арендатор может вести учёт в любой валюте, и вписанный узбекский сум
      будет так же неверен для казахстанского, как рубль для узбекского.
    */
    const hits = [...DOCS.matchAll(/\}\s*(руб\.|сум|so'm|тенге|₽)\b/g)].map(m => m[1]);
    expect(
      hits,
      "валюта вписана в разметку документа — она должна приходить из настроек:\n" + hits.join(", "),
    ).toEqual([]);
  });

  it("число мест не печатается выдуманным", () => {
    // «Итого мест: <b>1</b>» — счёт тарных единиц, которого система не ведёт.
    expect(DOCS).not.toMatch(/Итого мест:\s*<b>\s*\d/);
  });

  it("текстовые поля документа попадают на бумагу только через escapeHtml", () => {
    /*
      Правило общее, а не «эти два места».

      Проверка была узкой — искала ровно `${data.number}` — и пропустила
      подвал счёта: там дата стояла элементом массива,
      `[escapeHtml(footerNote), data.date].join(" • ")`, и экранирование
      обходилось стороной.

      Теперь из файла вырезаются комментарии и все вызовы escapeHtml(...), а
      в остатке ни одно строковое поле документа не должно стоять в позиции
      значения. Условие тернарника (`${data.notes ? … : ""}`) на бумагу не
      попадает — оно разрешено, и потому проверяется, что идёт за полем.
    */
    const FIELDS = [
      "number", "date", "listNumber", "currency", "notes", "footerNote",
      "shopOwner", "shopPhone", "territoryName", "paymentMethodLabel",
    ];
    const bare = DOCS
      .replace(/\/\*[\s\S]*?\*\//g, "")
      .replace(/<!--[\s\S]*?-->/g, "")
      .replace(/^[ \t]*\/\/.*$/gm, "")
      // Вложенность в один уровень скобок — глубже в этом файле не бывает.
      // Помощники экранируют сами: что они это делают, проверено ниже.
      .replace(/(escapeHtml|docFooter|metaRow|joinParts|partialNote)\([^()]*(?:\([^()]*\)[^()]*)*\)/g, "ESC");

    const offenders: string[] = [];
    for (const field of FIELDS) {
      // Значение — то, за чем сразу идёт конец подстановки, запятая,
      // закрытая скобка массива или конец строки-шаблона.
      const re = new RegExp("data\\." + field + "\\s*[}\\],`]", "g");
      for (const m of bare.matchAll(re)) {
        offenders.push(bare.slice(Math.max(0, m.index - 60), m.index + 30).replace(/\s+/g, " "));
      }
    }

    expect(
      offenders,
      "поле уходит в разметку без экранирования:\n" + offenders.join("\n"),
    ).toEqual([]);
  });

  it("состояние груза при приёмке не проставляется за кладовщика", () => {
    // Печаталось «Хорошее» в каждой строке приходной накладной: поля
    // condition в DocItem нет, приведение к Record<string, unknown> всегда
    // давало undefined. Кладовщик подписывает именно эту графу.
    expect(DOCS).not.toMatch(/condition\s*\?\?\s*"Хорошее"/);
    expect(DOCS).not.toMatch(/as Record<string, unknown>\)\.condition/);
  });

  it("ставка НДС и коды классификатора не подставляются числом", () => {
    /*
      В ТТН стояло «0%» в каждой строке, а в ТОРГ-12 — код ОКЕИ 796
      («штука») для любой единицы измерения. Учёта НДС в системе нет:
      api/services/onec-vat.ts к заказам не подключён. Обе бумаги — те, по
      которым сверяются с налоговой.
    */
    expect(DOCS, "ставка НДС вписана в строку товара").not.toMatch(/<td[^>]*>\s*0%\s*<\/td>/);
    expect(DOCS, "код ОКЕИ вписан в строку товара").not.toMatch(/<td[^>]*>\s*796\s*<\/td>/);
  });
});

describe("таблица документа сходится с собственной шапкой", () => {
  /*
    ── Зачем считать колонки ───────────────────────────────────────────────────

    В ТОРГ-12 шапка объявляла двенадцать граф, а строка заполняла их со
    сдвигом: артикул товара оказывался в графе «Код по ОКЕИ», количество
    печаталось дважды — во второй раз под заголовком «мест, штук», которого
    система не знает. Ошибка не роняет ничего и не видна в коде: и шапка, и
    строка по отдельности выглядят правильно.

    Здесь ширина считается по разметке: у шапки — наибольшая сумма colspan
    среди её строк, у каждой строки тела — своя сумма. Числа обязаны совпасть.
  */
  const span = (cell: string): number => {
    const m = cell.match(/colspan\s*=\s*"?(\d+)/i);
    return m ? Number(m[1]) : 1;
  };
  const rows = (html: string): string[] => html.match(/<tr[\s\S]*?<\/tr>/g) ?? [];
  const cells = (row: string): string[] => row.match(/<t[hd][\s\S]*?<\/t[hd]>/g) ?? [];
  const width = (row: string): number => cells(row).reduce((s, c) => s + span(c), 0);

  /*
    Строку, в которой графы подставляются переменной, пересчитать нельзя:
    сколько их будет, знает только вызов. Так устроены матрица по маршрутам
    (колонка на агента, ${agentCells}) и строка нумерации граф в ТОРГ-12
    (${Array.from(…)}). Такие строки не считаются вовсе — половина граф хуже,
    чем ни одной: она выдаёт выдуманное число за измеренное.
  */
  const isComputed = (row: string): boolean =>
    row.replace(/<t[hd][\s\S]*?<\/t[hd]>/g, "").includes("${");

  /** Ширина шапки и строки тела для каждой таблицы с thead и tbody. */
  const measured = (DOCS.match(/<table[\s\S]*?<\/table>/g) ?? [])
    .filter(t => t.includes("<thead") && t.includes("<tbody"))
    .map(table => {
      const head = table.slice(table.indexOf("<thead"), table.indexOf("</thead>"));
      const body = table.slice(table.indexOf("<tbody"));
      const headRows = rows(head).filter(r => !isComputed(r));
      const bodyRows = rows(body).filter(r => !isComputed(r));
      return {
        // Вторая графа: первая везде «№». `<th` c обязательным пробелом или
        // скобкой — иначе выражение цепляется за само `<thead>`.
        title: ([...head.matchAll(/<th(?:\s[^>]*)?>\s*([^<${]{1,28})/g)][1]?.[1] ?? "?").trim(),
        expected: headRows.length ? Math.max(...headRows.map(width)) : null,
        bodyRows,
      };
    })
    .filter(t => t.expected !== null && t.bodyRows.length > 0);

  it("считаются те таблицы, где есть что считать", () => {
    /*
      Иначе проверка ниже прошла бы на пустом списке и ничего не значила.

      Сюда попадают таблицы, где и шапка, и хотя бы одна строка тела написаны
      разметкой: расходная накладная, приходная и ТОРГ-12 — у них есть строки
      итогов. У счёта и пакетной накладной тело целиком собрано переменной
      (${itemRows}), считать в них нечего.
    */
    expect(measured.map(t => `${t.title}: ${t.expected} граф`)).toEqual([
      "Наименование товара: 6 граф",
      "Наименование товара: 5 граф",
      "Код товара: 11 граф",
    ]);
  });

  it("в каждой строке тела столько же граф, сколько в шапке", () => {
    const offenders: string[] = [];

    for (const { title, expected, bodyRows } of measured) {
      for (const row of bodyRows) {
        const w = width(row);
        if (w !== expected) {
          offenders.push(`«${title}»: шапка ${expected}, строка ${w} — ${row.replace(/\s+/g, " ").slice(0, 90)}`);
        }
      }
    }

    expect(offenders, "строка не сходится с шапкой:\n" + offenders.join("\n")).toEqual([]);
  });
});

describe("документы не занимают место впустую", () => {
  it("строка реквизита без значения не печатается", () => {
    /*
      Признак прежней беды: подстановка реквизита с запасным пустым значением
      прямо внутри строки-разметки. Значит строка нарисуется в любом случае, а
      после двоеточия окажется пусто.

      Исключение — бланк ТОРГ-12, где поле дозаполняют рукой: там пустое
      значение заменяется прочерком, и это видно по «|| "___».
    */
    const offenders: string[] = [];
    const re = /meta-label[^]{0,120}?escapeHtml\([a-zA-Z.]+\.(inn|address|bank|account|mfo|phone)\s*\?\?\s*""\)/g;
    for (const m of DOCS.matchAll(re)) offenders.push(m[0].slice(0, 80));

    expect(
      offenders,
      "реквизит печатается строкой даже когда его нет — используйте metaRow:\n" + offenders.join("\n"),
    ).toEqual([]);
  });

  it("помощники для этого заведены и делают, что обещают", () => {
    // Без этой проверки правило выше проходило бы и на пустом файле.
    expect(DOCS).toMatch(/function metaRow\(/);
    expect(DOCS).toMatch(/function joinParts\(/);
    // metaRow обязан возвращать пустоту на пустом значении — иначе он не
    // решает ту задачу, ради которой заведён.
    const body = DOCS.slice(DOCS.indexOf("function metaRow("), DOCS.indexOf("function joinParts("));
    expect(body).toMatch(/if\s*\(!v\)\s*return\s*""/);
  });

  it("помощники, которым доверено экранирование, экранируют", () => {
    /*
      Проверка выше вырезает вызовы metaRow, docFooter и partialNote вместе с
      аргументами — значит поле, отданное такому помощнику, она уже не видит.
      Доверие держится на том, что внутри стоит escapeHtml.
    */
    for (const name of ["metaRow", "docFooter", "partialNote"]) {
      const start = DOCS.indexOf(`function ${name}(`);
      expect(start, `${name} не найден`).toBeGreaterThan(-1);
      const body = DOCS.slice(start, DOCS.indexOf("\nfunction ", start + 1));
      expect(body, `${name} отдаёт значение в разметку без escapeHtml`).toMatch(/escapeHtml\(/);
    }
  });

  it("имя и адрес соединяются без висящей запятой", () => {
    // Стояло «${name}, ${address ?? ""}»: без адреса на бланке оставалась
    // запятая и пустота до конца строки.
    const dangling = [...DOCS.matchAll(/escapeHtml\([a-zA-Z.]+\.name\)\},\s*\$\{escapeHtml\([a-zA-Z.]+\.address/g)];
    expect(dangling.map(m => m[0]), "имя и адрес склеены запятой напрямую").toEqual([]);
  });
});
