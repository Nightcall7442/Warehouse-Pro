/**
 * Документы печатаются так, как нужно человеку, а не так, как решил код.
 *
 * ── Жалоба владельца ────────────────────────────────────────────────────────
 *
 * «Печать нельзя на альбомном, некрасивые, не компактные документы, вообще не
 * профессионально сделаны». Причины оказались техническими и повторялись во
 * всех шести местах, где приложение печатает.
 *
 * ── Правило 1: размер бумаги не объявляем ───────────────────────────────────
 *
 * `@page { size: A4 }` выглядит безобидно, но Chrome, увидев объявленный
 * size, ОТКЛЮЧАЕТ выбор ориентации в окне печати: страница сказала, чего
 * хочет, и человеку выбирать нечего. Именно отсюда «нельзя на альбомном».
 *
 * Бумагу выбирает тот, кто печатает: у него A4, Letter или рулон термо­
 * принтера. Поля объявлять можно и нужно — без них браузер берёт свои.
 *
 * ── Правило 2: окно не закрывается по таймеру ───────────────────────────────
 *
 * Стояло `setTimeout(() => w.close(), 800)` и даже 500. Окно печати
 * открывается асинхронно, и человек в нём выбирает принтер, ориентацию,
 * «Сохранить как PDF». Окно закрывалось у него под руками вместе с диалогом:
 * документ не печатался и не сохранялся, а выглядело это как сломанная
 * кнопка. Закрывать нужно по afterprint — он приходит и после печати, и
 * после отказа.
 *
 * ── Правило 3: шапка таблицы повторяется ────────────────────────────────────
 *
 * Без `thead { display: table-header-group }` накладная на сорок позиций со
 * второй страницы превращается в столбцы безымянных чисел.
 */
import { describe, it, expect } from "vitest";
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join, relative } from "node:path";

const SRC = join(__dirname, "..");

function walk(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    if (name === "node_modules") continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, out);
    else if (/\.(tsx?|css)$/.test(name)) out.push(full);
  }
  return out;
}

/** Файлы приложения без самих проверок. */
const FILES = walk(SRC)
  .filter(f => !relative(SRC, f).includes("__tests__"))
  .map(f => ({ rel: relative(SRC, f), text: readFileSync(f, "utf8") }));

describe("печать документов", () => {
  it("ни один @page не закрепляет размер бумаги", () => {
    const offenders: string[] = [];
    for (const { rel, text } of FILES) {
      // Внутри блока @page ищем объявление size.
      for (const m of text.matchAll(/@page[^{]*\{([^}]*)\}/g)) {
        if (/\bsize\s*:/.test(m[1])) offenders.push(`${rel}: @page {${m[1].trim()}}`);
      }
    }
    expect(
      offenders,
      "объявленный size отключает выбор ориентации в окне печати — человек не " +
      "сможет напечатать альбомом:\n" + offenders.join("\n"),
    ).toEqual([]);
  });

  it("окно печати не закрывается по таймеру", () => {
    const offenders: string[] = [];
    for (const { rel, text } of FILES) {
      // setTimeout, внутри которого закрывают окно.
      for (const m of text.matchAll(/setTimeout\([^;]{0,120}?\.close\(\)/g)) {
        offenders.push(`${rel}: ${m[0].replace(/\s+/g, " ").slice(0, 70)}`);
      }
    }
    expect(
      offenders,
      "окно закрывается раньше, чем человек успевает выбрать принтер — " +
      "закрывать нужно по afterprint:\n" + offenders.join("\n"),
    ).toEqual([]);
  });

  it("кнопка печати не печатает сам экран", () => {
    /*
      ── Правило 4: печатается документ, а не страница приложения ──────────────

      За значком принтера на «Отчётах» и на вкладке агентов стоял голый
      window.print(). Это печать САМОЙ СТРАНИЦЫ: тёмная заливка во весь лист,
      боковое меню, кнопки, полосы прокрутки, обрезанные графики. Снимок
      экрана, отправленный на принтер.

      Причём рядом, соседней кнопкой, уже собирался нормальный документ —
      период, карточки итогов, таблицы. Правильное действие было написано, но
      под другим значком.

      Ищется вызов из обработчика нажатия. В библиотеках печати window.print()
      законен: там его зовут ВНУТРИ окна с документом, а не на странице
      приложения.
    */
    const offenders: string[] = [];
    for (const { rel, text } of FILES) {
      for (const m of text.matchAll(/onClick=\{[^}]{0,40}window\.print\(\)/g)) {
        offenders.push(`${rel}: ${m[0].replace(/\s+/g, " ")}`);
      }
    }
    expect(
      offenders,
      "кнопка отправит на принтер снимок экрана вместо документа:\n" + offenders.join("\n"),
    ).toEqual([]);
  });

  it("заблокированное окно печати не подменяется печатью экрана", () => {
    /*
      Сборщики документов открывают окно и пишут в него. При заблокированном
      окне стояло `if (!w) { window.print(); return; }` — то есть на принтер
      уходила страница приложения, и человек получал снимок экрана вместо
      накладной, без единого слова о причине.

      Блокировка всплывающих окон — обычная настройка браузера и чинится
      галочкой в адресной строке; про неё и надо сказать.
    */
    const offenders: string[] = [];
    for (const { rel, text } of FILES) {
      // Комментарии снимаются: прежний вид кода описан словами прямо в них, и
      // без этого правило ловило бы собственное объяснение.
      const code = text
        .replace(/\/\*[\s\S]*?\*\//g, "")
        .replace(/^[ \t]*\/\/.*$/gm, "");
      for (const m of code.matchAll(/if\s*\(!\w+\)\s*\{\s*window\.print\(\)/g)) {
        offenders.push(`${rel}: ${m[0].replace(/\s+/g, " ")}`);
      }
    }
    expect(
      offenders,
      "вместо объяснения печатается экран:\n" + offenders.join("\n"),
    ).toEqual([]);
  });

  it("валюта нигде не вписана словом", () => {
    /*
      ── Правило 4: валюту знают настройки, а не разметка ──────────────────────

      «сум» стояло вписанным в девятнадцати местах: в карточках выгрузки
      «Доходы и расходы», в итоге выгрузки заказов, в накладной прихода, в
      карточках складского PDF и запасными значениями у printBatchInvoices и
      printLoadingList. Символ валюты арендатор задаёт в настройках, и во всех
      этих файлах он был под рукой — useCurrency() или параметр функции.

      Ищем валюту сразу после закрытой подстановки: это и есть подпись к
      только что напечатанному числу. Слово «сумма» правилу не мешает — после
      «сум» там идёт буква, а не граница слова.
    */
    const offenders: string[] = [];
    for (const { rel, text } of FILES) {
      for (const m of text.matchAll(/\}\s*(сум|so'm|руб\.|тенге|₽)\b/g)) {
        offenders.push(`${rel}: ${text.slice(Math.max(0, m.index - 45), m.index + 18).replace(/\s+/g, " ")}`);
      }
    }
    expect(
      offenders,
      "валюта вписана в разметку — организация с другой валютой получит чужую " +
      "подпись под своими деньгами:\n" + offenders.join("\n"),
    ).toEqual([]);
  });

  it("документ с таблицей повторяет её шапку на каждой странице", () => {
    /*
      Проверяются только те файлы, что собирают документ для печати целиком:
      признак — объявленный в них @page. Экраны приложения сюда не попадают,
      их печать накрывают общие правила из index.css.
    */
    const offenders: string[] = [];
    for (const { rel, text } of FILES) {
      if (!/@page/.test(text)) continue;
      if (!/<table|<\/table>|table\s*\{/.test(text)) continue;
      if (!/table-header-group/.test(text)) offenders.push(rel);
    }
    expect(
      offenders,
      "шапка таблицы не повторяется: со второй страницы документ становится " +
      "столбцами безымянных чисел:\n" + offenders.join("\n"),
    ).toEqual([]);
  });
});
