/**
 * У всех графиков мониторинга одна ось времени.
 *
 * ── Что было ────────────────────────────────────────────────────────────────
 *
 * Владелец прислал снимок страницы. Под каждым графиком стояли подписи:
 *
 *     19:52:58   19:53:33   19:53:59   19:51:52   19:52:47   19:53:52
 *
 * Время шло вперёд, а потом прыгало на две минуты назад. Линии запросов
 * обрывались на двух третях ширины, а память рисовалась отдельным куском в
 * последней трети — и выглядело это так, будто память появилась только что.
 *
 * Причина: четыре ряда сливались в Map и отдавались в порядке ВСТАВКИ. Ряды
 * запросов пишутся по целым секундам и только когда запрос был; память — раз в
 * пять секунд по произвольной миллисекунде. Ключи памяти не совпадали с
 * ключами запросов, поэтому создавались заново и ложились в конец, начиная
 * отсчёт заново.
 *
 * ── Правило ─────────────────────────────────────────────────────────────────
 *
 * Точка на оси есть всегда, а не только когда кто-то что-то записал. Тогда
 * всплеск времени ответа можно приложить к всплеску очереди за соединением —
 * ради этого графики и рисуют.
 */
import { describe, it, expect } from "vitest";
import { buildMetricGrid, type SeriesMap } from "@/lib/metric-grid";

const T = 1_757_000_000_000; // произвольный момент, кратный секунде

/** Ряд из точек: [сдвиг в секундах от T, значение]. */
function series(points: Array<[number, number]>) {
  return { data: points.map(([sec, value]) => ({ timestamp: T + sec * 1000, value })) };
}

describe("сетка графиков", () => {
  it("время идёт только вперёд", () => {
    /*
      Ровно тот случай со снимка: запросы за первые секунды, память — позже и
      по своим отметкам. Раньше это давало ось, уходящую вспять.
    */
    const s: SeriesMap = {
      req_per_sec:  series([[0, 5], [1, 7], [2, 3]]),
      heap_used_mb: series([[0.4, 70], [5.4, 74], [10.4, 78]]),
    };

    const rows = buildMetricGrid(s, 12);
    const clocks = rows.map(r => r.time);

    expect(clocks).toEqual([...clocks].sort());
    expect(new Set(clocks).size, "секунда встречается дважды").toBe(clocks.length);
  });

  it("у каждой секунды окна есть точка", () => {
    const s: SeriesMap = { req_per_sec: series([[0, 1]]) };
    // Без сплошной сетки соседние графики нельзя приложить друг к другу: у
    // каждого своя ось из тех мгновений, когда именно ему было что записать.
    expect(buildMetricGrid(s, 60)).toHaveLength(60);
    expect(buildMetricGrid(s, 120)).toHaveLength(120);
  });

  it("отсутствие запросов — это ноль, а не пробел", () => {
    const s: SeriesMap = { req_per_sec: series([[0, 4], [3, 6]]) };
    const rows = buildMetricGrid(s, 4);
    // Окно кончается на последней точке: секунды 0,1,2,3 от T.
    expect(rows.map(r => r.rps)).toEqual([4, 0, 0, 6]);
  });

  it("память между замерами держит последнее значение", () => {
    const s: SeriesMap = {
      req_per_sec:  series([[0, 1], [1, 1], [2, 1], [3, 1], [4, 1], [5, 1]]),
      heap_used_mb: series([[0, 70], [5, 90]]),
    };
    const rows = buildMetricGrid(s, 6);
    /*
      Ноль вместо пропущенного замера означал бы падение памяти до нуля четыре
      секунды из каждых пяти — на графике это выглядит как авария, которой нет.
    */
    expect(rows.map(r => r.heap)).toEqual([70, 70, 70, 70, 70, 90]);
  });

  it("уровень, замеренный до начала окна, не теряется", () => {
    const s: SeriesMap = {
      req_per_sec:  series([[100, 2]]),
      // Замер сделан задолго до окна и больше не повторялся.
      heap_used_mb: series([[0, 64]]),
    };
    const rows = buildMetricGrid(s, 5);
    // Иначе график памяти был бы пуст при живом сборе.
    expect(rows.every(r => r.heap === 64)).toBe(true);
  });

  it("ряды насыщения доезжают до графиков", () => {
    const s: SeriesMap = {
      req_per_sec:      series([[0, 1], [1, 1]]),
      max_response_ms:  series([[0, 900], [1, 120]]),
      db_pool_busy:     series([[0, 3]]),
      db_pool_queue:    series([[0, 2]]),
      event_loop_lag_ms:series([[0, 45]]),
      rss_mb:           series([[0, 180]]),
    };
    const last = buildMetricGrid(s, 2).at(-1)!;

    // Худший ответ — то, из-за чего жалуются; по среднему его не увидеть.
    expect(last.worst).toBe(120);
    expect(last.dbBusy).toBe(3);
    expect(last.dbQueue).toBe(2);
    expect(last.lag).toBe(45);
    // Предел контейнера считается по RSS, а не по куче.
    expect(last.rss).toBe(180);
  });

  it("«сейчас» берётся из данных, а не с часов браузера", () => {
    /*
      Часы посетителя могут отличаться от серверных на минуты. Если строить
      окно от Date.now(), оно уехало бы целиком, и графики оказались бы пустыми
      при совершенно исправном сборе.
    */
    const old: SeriesMap = { req_per_sec: series([[-100_000, 9]]) };
    const rows = buildMetricGrid(old, 3);
    expect(rows).toHaveLength(3);
    expect(rows.at(-1)!.rps).toBe(9);
  });

  it("пустой сбор — пустые графики, а не строка нулей", () => {
    // Нули нарисовали бы ровную линию «всё спокойно» там, где данных нет вовсе.
    expect(buildMetricGrid({}, 60)).toEqual([]);
    expect(buildMetricGrid({ req_per_sec: { data: [] } }, 60)).toEqual([]);
  });
});
