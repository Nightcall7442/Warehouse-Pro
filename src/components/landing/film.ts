/** Первая ширина, которой хватает на экран (в физических точках); шире всех — последняя. */
export function pickFilmWidth(widths: readonly number[], screenPx: number): number {
  return widths.find(w => w >= screenPx) ?? widths[widths.length - 1];
}

/**
 * Видимость строки на отрезке [from, to] прогресса: полная внутри, у краёв
 * гаснет на ширине edge. В отличие от captionOpacity, края секции особыми не
 * считаются: первая строка появляется уже после закрепления кадра, последняя
 * уходит до того, как кадр начнёт сворачиваться, — так строка не режется
 * краем окна, пока секция въезжает (снимок владельца 19.09.2026).
 */
export function windowOpacity(p: number, from: number, to: number, edge: number): number {
  const a = Math.min(1, Math.max(0, (p - from) / edge));
  const b = Math.min(1, Math.max(0, (to - p) / edge));
  return Math.min(a, b);
}

/**
 * Насколько кадр «вставка» (1) или «во весь экран» (0). В начале секции кадр
 * лежит листом с полями и скруглением внутри ночной полосы и за первые lead
 * прогресса раскрывается на весь экран; в конце — сворачивается обратно.
 * Так у плёнки есть вход и выход, а не обрыв по краю.
 */
export function frameInset(p: number, lead = 0.07): number {
  const k = Math.min(1, Math.max(0, Math.min(p / lead, (1 - p) / lead)));
  return 1 - (1 - (1 - k) * (1 - k)); // ease-out: раскрывается быстро, дотягивает плавно
}
