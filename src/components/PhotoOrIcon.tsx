import { useState, type ReactNode, type CSSProperties } from "react";

/**
 * Фотография — или запасной вид, если её нет ИЛИ она не открылась.
 *
 * ── Зачем ───────────────────────────────────────────────────────────────────
 *
 * Экраны рисовали <img> всякий раз, когда в поле что-то лежало, и молча
 * полагались на то, что оно откроется. Не открывшаяся картинка — это не
 * пустота: браузер рисует на её месте свой знак поломки (на iPhone — синий
 * квадратик с вопросом), и экран выглядит сломанным, хотя сломано ровно одно
 * поле в одной строке базы.
 *
 * Так и вышло в каталоге агента: импорт из Excel клал в поле имя файла из
 * колонки «фото», оно доезжало до тега img, и карточки стояли с битыми
 * картинками. Сервер такие значения больше не отдаёт (api/lib/photo-url.ts),
 * но интернет ненадёжен и без них: ссылка была верной вчера и перестала быть
 * сегодня. Поэтому отказ показа приравнивается к «фотографии нет».
 *
 * Запасной вид приходит снаружи целиком: у товара это коробка, у магазина —
 * лавка, у фотоотчёта — свой значок, и каждый экран красит его по-своему.
 * Компонент отвечает ровно за одно — открылась картинка или нет.
 */
export function PhotoOrIcon({ src, fallback, alt = "", lazy = true, className, style }: {
  src?: string | null;
  /** Что показать вместо снимка: значок товара, лавки, отчёта. */
  fallback: ReactNode;
  alt?: string;
  /** Крупный снимок в открытой шторке нужен сразу, а не по прокрутке. */
  lazy?: boolean;
  className?: string;
  style?: CSSProperties;
}) {
  /*
    Запоминается САМА не открывшаяся ссылка, а не признак «не открылось».

    С признаком пришлось бы гасить его эффектом на смену src — то есть менять
    состояние из эффекта, лишний проход отрисовки и правило линтера поперёк. А
    так новая ссылка не совпадает с запомненной, и попытка начинается заново
    сама собой: заменил оператор фотографию — она показалась, без перезагрузки.
  */
  const [failedSrc, setFailedSrc] = useState<string | null>(null);

  if (!src || failedSrc === src) return <>{fallback}</>;

  return (
    <img
      src={src}
      alt={alt}
      loading={lazy ? "lazy" : undefined}
      onError={() => setFailedSrc(src)}
      className={className}
      style={style ?? (className ? undefined : { width: "100%", height: "100%", objectFit: "cover" })}
    />
  );
}
