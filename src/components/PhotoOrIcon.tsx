import { useState } from "react";
import { Package } from "lucide-react";

/**
 * Фотография — или значок, если её нет ИЛИ она не открылась.
 *
 * ── Зачем ───────────────────────────────────────────────────────────────────
 *
 * Карточка товара рисовала <img> всякий раз, когда в поле что-то лежало, и
 * молча полагалась на то, что оно откроется. Не открывшаяся картинка — это не
 * пустота: браузер рисует на её месте свой знак поломки (на iPhone — синий
 * квадратик с вопросом), и экран выглядит сломанным, хотя сломано ровно одно
 * поле в одной строке базы.
 *
 * Причин не открыться довольно: ссылка на чужой сайт, который её больше не
 * отдаёт; адрес по http, который блокирует политика безопасности страницы;
 * просто имя файла, попавшее в базу из выгрузки. Сервер теперь такие значения
 * не отдаёт вовсе (api/lib/photo-url.ts), но интернет ненадёжен и без них:
 * ссылка была верной вчера и перестала быть сегодня.
 *
 * Поэтому отказ показа приравнивается к «фотографии нет» — так человек видит
 * привычный значок товара, а не знак поломки.
 */
export function PhotoOrIcon({ src, iconSize, iconColor, lazy = true }: {
  src?: string | null;
  iconSize: number;
  iconColor?: string;
  /** Крупный снимок в открытой шторке нужен сразу, а не по прокрутке. */
  lazy?: boolean;
}) {
  /*
    Запоминается САМА не открывшаяся ссылка, а не признак «не открылось».

    С признаком пришлось бы гасить его эффектом на смену src — то есть менять
    состояние из эффекта, лишний проход отрисовки и правило линтера поперёк. А
    так новая ссылка не совпадает с запомненной, и попытка начинается заново
    сама собой: заменил оператор фотографию — она показалась, без перезагрузки.
  */
  const [failedSrc, setFailedSrc] = useState<string | null>(null);

  if (!src || failedSrc === src) {
    return <Package size={iconSize} style={{ color: iconColor ?? "var(--color-text-tertiary)" }} />;
  }

  return (
    <img
      src={src}
      alt=""
      loading={lazy ? "lazy" : undefined}
      onError={() => setFailedSrc(src)}
      style={{ width: "100%", height: "100%", objectFit: "cover" }}
    />
  );
}
