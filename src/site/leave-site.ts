/**
 * Уйти со страницы сайта настоящей загрузкой, заменив текущую запись истории.
 *
 * Отдельной функцией, чтобы проверка могла подменить её: jsdom навигацию не
 * выполняет, а сама замена — ровно то, что стоит проверить.
 */
export function leaveSite(url: string): void {
  window.location.replace(url);
}
